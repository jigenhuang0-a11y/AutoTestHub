qa("Q18. Self-Attention的Q/K/V矩阵怎么来的？计算复杂度？",
'''【L1·回答】
Q=W_Q·X, K=W_K·X, V=W_V·X。三个都是输入X的线性投影。计算：QK^T得注意力分数(N×N)→Softmax→乘V。复杂度O(N²·d)，N是序列长度，d是维度。

【L2追问】为什么Q和K用不同权重？用同一个会怎样？
【L2·回答】
用不同权重增加表达能力——让模型学习"查询什么"和"被查询什么"的不同表示。如果W_Q=W_K，则注意力矩阵对称，限制模型能力。语言建模中"A依赖B"≠"B依赖A"，非对称注意力更好。

【L3追问】如果QKV全换成同一个权重矩阵呢？
【L3·回答】
能工作但性能下降——所有注意力共享同一投影空间，损失不同Head关注不同子空间的能力。实验证明性能下降约2-5%。但参数量减少，极低资源场景可能是合理权衡。本质是"表达能力"和"参数效率"的trade-off。

【L4追问】Multi-Head Attention中不同Head真的学到不同东西吗？
【L4·回答】
通过注意力可视化验证：某些Head专注相邻Token(局部语法)、某些关注远距离依赖(指代消解)、某些对特定POS敏感。剪枝实验证明可移除30%Head而性能几乎不变——存在大量冗余。不同层Head重要性不同：中间层冗余最高，底层和顶层更重要。''')

qa("Q19. 位置编码有哪些方式？RoPE为什么能外推？",
'''【L1·回答】
四种：①正弦编码(sin/cos)——无需训练，理论可外推；②可学习编码(BERT/GPT)——灵活但不可外推；③RoPE(LLaMA/Qwen)——旋转矩阵编码相对位置，外推好；④ALiBi(Bloom)——线性偏置惩罚远距离。

【L2追问】RoPE的数学原理？
【L2·回答】
RoPE将d维向量拆成d/2对，每对做2D旋转。旋转角=pos·θ_i，θ_i=10000^{-2i/d}。Q和K都旋转后：Q_m^T·K_n只依赖相对位置(m-n)。旋转矩阵是正交矩阵，保持向量模长不变。

【L3追问】为什么RoPE外推比正弦编码好？
【L3·回答】
RoPE的外推更自然——相对位置关系(m-n)本身就是训练时见过的(短序列的相对位置=长序列的相对位置)，模型不需学习新位置模式。但超长外推(4K→128K)也需要位置插值(Position Interpolation)辅助——通过缩放θ_i让长序列的相对位置落在训练分布内。

【L4追问】位置插值的具体做法？
【L4·回答】
线性插值：将位置索引除以缩放因子(如4K→32K，factor=8)。修改旋转频率θ_i→θ_i/factor。效果：训练时位置0-4095的旋转模式→直接映射到推理时位置0-32767。但线性插值会"压缩"高频位置信息→NTK-aware插值(非线性缩放)更好——低频少缩放，高频多缩放。''')

qa("Q20. LayerNorm和BatchNorm的区别？为什么LLM用LayerNorm？",
'''【L1·回答】
BN对batch内同特征维归一化(N×1)；LN对单样本所有特征归一化(1×d)。LLM用LN原因：①序列长度可变→BN统计量不稳定；②自回归推理batch=1→BN无法计算；③LN不依赖batch统计，训练推理一致。

【L2追问】RMS Norm是什么？为什么LLaMA用它？
【L2·回答】
RMS Norm=LayerNorm去掉中心化(不减均值，只缩放)。计算：x·RMS(x)^{-1}·γ。优势：计算更快(省均值计算)，实验证明和LN效果相当。LLaMA/LLaMA2/T5都用。

【L3追问】Pre-Norm vs Post-Norm的本质区别？
【L3·回答】
Pre-Norm: Norm→Sublayer→+Residual(先归一化再做子层)。Post-Norm: Sublayer→Norm→+Residual(先做子层再归一化)。Post-Norm效果略好但训练不稳定(需warmup)，Pre-Norm训练更稳定(梯度流更平滑)。深层原因：Pre-Norm让残差路径的恒等映射保持干净(不被Norm干扰)，利于深层网络训练。

【L4追问】为什么去掉中心化(均值)对Transformer影响不大？
【L4·回答】
直觉：Transformer中的残差连接已经提供了"均值调整"的能力——每个子层的输出加回输入，自然可以做类似中心化的操作。RMS Norm只做缩放(控制方差)，把"中心化"交给残差连接和后续线性变换。实验验证：去掉中心化不降性能，但省计算。''')

qa("Q21. 残差连接为什么对深层Transformer至关重要？",
'''【L1·回答】
残差=F(x)+x。作用：①缓解梯度消失——梯度通过残差路径直传底层；②恒等映射——初始时子层输出≈0，深层性能≥浅层；③特征复用——低层特征直传高层。无残差：>12层极难训练。

【L2追问】梯度消失的具体机制？
【L2·回答】
反向传播链式法则连乘。每层梯度<1→连乘指数衰减→底层梯度≈0。残差：梯度=∂L/∂x·(1+∂F/∂x)，"1"来自恒等路径(导数为1)→保证梯度至少原样传到前一层。

【L3追问】残差连接和Highway Network、DenseNet的关系？
【L3·回答】
残差：y=F(x)+x(加性)。Highway Network：y=T(x)·F(x)+(1-T(x))·x(门控)。DenseNet：y=[F(x),x](拼接+所有前层)。残差最简单但有效——恒等映射保证了深层不比浅层差。DenseNet特征复用更充分但显存大。Highway Network门控更灵活但需额外参数。Transformer选残差是因为简洁高效。

【L4追问】如果残差连接去掉会怎样？实验证据？
【L4·回答】
原Transformer论文实验：无残差时，20层模型的训练loss不下降(梯度消失)，6层勉强可训练。有残差时，20层甚至更深都可训练。ResNet论文(CV领域)的经典实验：34层无残差→训练误差反而比18层高(退化问题)，34层有残差→比18层好。''')

qa("Q22. FFN在Transformer中的作用？SwiGLU是什么？",
'''【L1·回答】
FFN=两层全连接+激活：W2·Activation(W1·x)。作用：①Token内非线性变换(自注意力管Token间交互)；②知识存储——FFN层存大量事实知识(类似Key-Value记忆)。SwiGLU=Swish门控替代ReLU。

【L2追问】FFN存知识的证据？
【L2·回答】
证据：①知识编辑实验——修改FFN特定权重可精确修改模型对特定事实的输出；②神经元激活分析——某些神经元对特定概念选择性激活；③Attention管"从哪取信息"，FFN管"存储什么信息"。模型越大(FFN越大)知识越多。

【L3追问】SwiGLU门控机制的本质？比ReLU好在哪？
【L3·回答】
SwiGLU=两个线性变换→一个用Swish激活→元素乘。门控本质：动态控制信息流动(类似LSTM门)。ReLU是硬阈值(负值全截断→梯度死区)，Swish平滑非单调(负值小非零)→梯度流更好。门控让模型学习"哪些信息通过"而非固定激活函数。

【L4追问】为什么门控激活函数(GLU variants)在大模型中效果更好？
【L4·回答】
GLU变体(SwiGLU/GeGLU)的共同点：输入通过两个线性变换→一个激活→元素乘。直觉：一个分支学习"内容"(what)，另一个分支学习"门控"(how much)。这种分离让模型更灵活地控制信息流。实验：PaLM用SwiGLU替代ReLU→同等计算量下显著提升。LLaMA/LLaMA2/Gemma均采用SwiGLU。''')

qa("Q23. Flash Attention解决了什么问题？分块计算原理？",
'''【L1·回答】
解决Attention显存/速度瓶颈。标准Attention的QK^T矩阵N×N读写HBM开销大。Flash Attention：①分块计算(Tiling)——Q/K/V切块在SRAM逐块算softmax；②重计算——反向传播重算注意力矩阵。效果：显存O(N²)→O(N)，速度2-4倍。

【L2追问】分块计算softmax怎么保证数学等价？
【L2·回答】
Online Softmax技巧：维护running max和running sum。新块→更新max→用新旧max差值修正已有结果→合并。数学等价于全局softmax，但迭代计算避免存完整矩阵。

【L3追问】Flash Attention对硬件有什么要求？
【L3·回答】
核心是IO优化：HBM(显存)容量大带宽有限，SRAM(片上缓存)容量小带宽极高。Flash Attention把计算搬到SRAM→只读写最终结果到HBM。要求GPU支持高效SRAM(Ampere架构以上A100/H100)。这是软硬件协同优化的典型案例。

【L4追问】Flash Attention 2相比v1改进了什么？
【L4·回答】
FA2改进：①减少非矩阵乘法操作(softmax重计算从两步变一步)；②优化线程块调度(更好的并行度)；③前向2x加速，反向1.5x。核心洞察：FA1把Q当外循环→并行度受序列长度限制。FA2把Q和KV都当外循环→更好的GPU利用率。''')

qa("Q24. KV Cache是什么？显存占用怎么算？GQA/MQA怎么减少？",
'''【L1·回答】
自回归推理每步生成一个Token，每步需对历史Token做Attention。KV Cache：缓存历史K/V矩阵，新Token只算自己的Q。第N步计算量从O(N²)降到O(N)。

【L2追问】显存占用公式？
【L2·回答】
占用=2×层数×KV头数×每头维度×序列长度×精度(FP16=2字节)×Batch。例：LLaMA-7B(32层×32头×128维)→1K token→512MB；100K→50GB。长序列是推理的主要显存瓶颈。

【L3追问】GQA/MQA怎么减少KV Cache？
【L3·回答】
MQA：所有Q头共享一组K/V(KV头=1)→KV Cache减少到1/h。GQA：Q头分组同组共享K/V→减少到groups/h。LLaMA2用GQA(8组)，KV Cache减少8倍，质量损失极小。

【L4追问】GQA为什么几乎不损失质量？
【L4·回答】
MQA(1组KV)有一定质量损失(尤其长文本)。GQA(如8组)是MHA(全头)和MQA的折中。直觉：K/V矩阵主要编码"位置和内容"，不需要和Q一样的细粒度。实验：8组GQA vs 32头MHA→基准测试差异<1%。但训练时仍需MHA(保证学习能力)，推理时转换为GQA(节省显存)。''')

qa("Q25. 采样策略有哪些？Temperature/Top-p/Top-k区别？",
'''【L1·回答】
Temperature(T)：对logits除以T再softmax，T>1更随机，T<1更确定，T→0=贪心。Top-k：只从概率最高的k个Token采样。Top-p(核采样)：累积概率≥p的最小Token集合采样(动态k)。

【L2追问】各自适用场景？
【L2·回答】
Top-k固定截断→对分布敏感。Top-p动态截断→适应不同分布。创意任务(写诗)→高T+高p；事实任务(QA)→低T+低p；代码生成→贪心(T=0)保证确定性。

【L3追问】为什么采样而不是选概率最高的？
【L3·回答】
选最高(贪心)→输出重复单调。采样引入随机性→更多样输出。必须采样：创意写作/对话(需要多样性)。不需要：代码生成/事实问答(需要确定性)。本质是"探索vs利用"的权衡。

【L4追问】Temperature=0是否保证确定性？
【L4·回答】
理论上T=0=贪心解码(argmax)，应该确定性。但实际上GPU浮点运算的非确定性(并行归约顺序不同→浮点舍入误差→logits微小差异→两个Token概率极其接近时可能选不同Token)。OpenAI API的seed参数是best-effort(不保证100%确定性)。AI测试中不能期待100%可复现。''')

