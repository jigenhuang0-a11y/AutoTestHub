qa("Q38. RAG的完整流程？每个环节的测试重点？",
'''【L1·回答】
RAG流程：用户Query→检索(Retrieval)→增强(Augmentation)→生成(Generation)→回答。测试重点：①检索——召回率/精确率/排序质量；②增强——上下文是否被正确注入Prompt；③生成——Faithfulness(不编造)/Relevancy(不跑题)；④端到端——整体质量+延迟。

【L2追问】检索环节怎么测试？
【L2·回答】
用标注数据集(Query→相关文档)计算Recall@K/Precision@K/MRR/NDCG。测试不同Query类型(关键词/自然语言/模糊查询)。边界case：空查询/超长查询/多语言查询/同义词查询。检索是RAG的入口，检索质量决定生成上限。

【L3追问】怎么构造RAG评测标注数据集？
【L3·回答】
①人工标注——领域专家为每个Query标注相关文档(最可靠但贵)；②半自动——用大模型生成Query+检索结果反标注(需人工校验)；③合成——用文档自动生成QA对。我们混合使用：核心场景人工标注+一般场景半自动。

【L4追问】半自动标注怎么控制质量？
【L4·回答】
①人工抽样校验——自动生成后随机抽10%人工评分，通过率<80%重新生成；②一致性检查——同一文档不应生成矛盾QA对；③多样性检查——Query类型分布(事实/推理/比较/总结)要均衡；④难度分级——简单(直接匹配)/中等(需推理)/困难(需综合多文档)。''')

qa("Q39. RAG的Chunking策略有哪些？Chunk Size怎么选？",
'''【L1·回答】
Chunking策略：①固定长度——按Token数切分(如512 tokens)，简单但可能切断语义；②语义切分——按段落/句子边界切分；③递归切分——先用大分隔符再小分隔符；④滑动窗口——重叠切分(overlap=50 tokens)。

【L2追问】Chunk Size大小各有什么影响？
【L2·回答】
大Chunk(1024+ tokens)：上下文更完整→回答更完整，但检索精度下降(噪声多)+Token成本高。小Chunk(128-256 tokens)：检索精度高+成本低，但可能切断关键信息→回答不完整。实践：256-512 tokens是常见平衡点，根据文档类型调整。

【L3追问】Chunking策略对评测指标有什么影响？
【L3·回答】
直接影响Context Precision和Context Recall。小chunk→Precision高(检索精准)但Recall低(可能漏信息)。大chunk→Recall高(覆盖全)但Precision低(夹杂无关内容)。评测时需记录Chunking参数做A/B对比。RAGAS的Context Precision/Recall正好量化这个trade-off。

【L4追问】overlap(重叠)的作用？多少合适？
【L4·回答】
Overlap=相邻chunk共享的Token数。作用：防止关键信息刚好在chunk边界被切断。典型值：chunk_size的10-20%(如512 tokens→overlap=50-100)。太大→冗余多+成本高；太小→边界信息丢失。实测：overlap=chunk_size×15%通常最优。''')

qa("Q40. Embedding模型怎么选？怎么评测？",
'''【L1·回答】
选型维度：语言支持(中文/多语言)、向量维度(影响存储和速度)、最大序列长度(影响Chunking)、性能(MTEB基准排名)。代表：OpenAI text-embedding-3、BGE(中文强)、Jina AI。

【L2追问】MTEB基准怎么解读？
【L2·回答】
MTEB包含8大类任务：分类/聚类/配对/重排序/检索/STS/摘要/双文本。关注检索任务分数(最相关RAG场景)和中文子集分数。不同维度版本的分数vs维度trade-off——维度越低存储越小但性能可能下降。

【L3追问】如果MTEB高分但实际RAG效果不好，为什么？
【L3·回答】
可能原因：①MTEB是通用评测，不反映特定领域(如车载技术文档)的语义理解；②Embedding和生成模型的配合——检索到了但生成模型不理解；③评测数据分布和实际数据分布不一致。解决：构造领域特定评测集(用自己的文档+人工标注相关性)。

【L4追问】怎么构造领域特定的Embedding评测集？
【L4·回答】
①收集领域文档(如车载用户手册/技术文档)；②人工或半自动生成Query+标注相关文档；③设计不同难度Query(直接匹配/语义相似/需要推理)；④对比不同Embedding模型的Recall@K和MRR；⑤定期更新评测集(防止过拟合)。这是RAG评测基础设施的核心。''')

qa("Q41. Rerank(重排序)是什么？什么时候需要？",
'''【L1·回答】
Rerank：检索后用更强模型对候选文档做精细排序。初检用Embedding(速度快)召回Top-K→Rerank用Cross-Encoder(精度高)精排Top-N。提升检索精度10-20%。

【L2追问】Cross-Encoder和Bi-Encoder的本质区别？
【L2·回答】
Bi-Encoder：Query和Document独立编码→向量相似度(快但交互浅)。Cross-Encoder：Query和Document拼接后一起编码→全交互(慢但精度高)。Rerank用Cross-Encoder对初检候选精排——兼顾速度和精度。

【L3追问】Rerank的延迟和成本怎么控制？
【L3·回答】
①控制候选数——初检索取Top-50→Rerank只处理50个；②模型选择——小Cross-Encoder(如MiniLM)比大模型快10倍；③缓存——高频Query的Rerank结果缓存；④批处理——多Query一起Rerank提高GPU利用率。评测时需测试初检K值vs延迟vs精度的trade-off。

【L4追问】Rerank在什么场景ROI最高？
【L4·回答】
ROI高场景：①高精度需求(医疗/法律/车载安全)→Rerank必加；②长尾Query(罕见查询)→Embedding可能不准确→Rerank补偿；③多文档综合问答→需要精细判断哪些文档真正有用。ROI低场景：①简单FAQ(Embedding已足够准)；②极高吞吐场景(Rerank的延迟不可接受)。''')

qa("Q42. RAGAS四个指标的计算方法和局限？",
'''【L1·回答】
Faithfulness：拆claims→LLM判断是否被context支持。Answer Relevancy：反推问题→和原问题计算语义相似度。Context Precision：检索到的上下文中真正有用的比例。Context Recall：答案所需信息在上下文中的覆盖度。

【L2追问】每个指标的LLM Prompt模板？
【L2·回答】
Faithfulness Prompt："Given the context: {context}, is the claim '{claim}' supported? Answer YES or NO." Relevancy Prompt："For the sentence '{sentence}', generate a question it answers." Precision/Recall需要标注哪些上下文是相关的。

【L3追问】如果RAGAS指标都很好但实际体验差，为什么？
【L3·回答】
可能原因：①指标覆盖不全——RAGAS只管四维度，不管有用性/可读性/安全性；②Judge模型偏差——LLM-as-Judge的固有偏差(位置/长度/自我偏好)；③标注质量问题；④分布偏移——评测数据和真实Query分布不一致。

【L4追问】怎么校准RAGAS指标？
【L4·回答】
①每月抽样100条人工评分vs RAGAS评分→计算Cohen's Kappa；②κ>0.8=高度一致，<0.6=需调整评测Prompt或换Judge模型；③追踪κ长期趋势(防漂移)；④人工评分也需一致性校验(Fleiss' Kappa)。核心：RAGAS不是绝对真理，需要持续和人工对标。''')

qa("Q43. Hybrid Search(混合检索)怎么做？RRF是什么？",
'''【L1·回答】
混合检索=向量检索(语义)+关键词检索(BM25/TF-IDF)。互补：向量找语义相关(但不精确)，关键词找精确匹配(但不懂语义)。融合方式：RRF(Reciprocal Rank Fusion)——合并排序结果(1/(k+rank)求和)；加权分数——向量分数×α+关键词分数×(1-α)。

【L2追问】RRF的k参数怎么选？α权重怎么调？
【L2·回答】
RRF的k默认60(经典值)，调大→排名差异影响变小。α权重：用标注数据集网格搜索最优值。实践：α=0.7(偏向量)到α=0.5(均衡)。不同Query类型最优α不同(精确查询→α小，模糊查询→α大)。

【L3追问】混合检索在评测中怎么测试？
【L3·回答】
①分别测试纯向量/纯关键词/混合检索的Recall@K→验证混合优于单独；②按Query类型分组分析(精确/模糊/多义词)→看不同策略适用场景；③延迟测试——混合检索比纯向量慢(需额外BM25计算)，评估延迟增加是否可接受。

【L4追问】BM25和TF-IDF的区别？
【L4·回答】
TF-IDF：词频×逆文档频率。BM25改进：①饱和词频(词频增加→权重增长递减，防止长文档优势)；②文档长度归一化(惩罚长文档)。BM25在检索任务上几乎总是优于TF-IDF。但两者都不懂语义——这是向量检索互补的地方。''')

qa("Q44. RAG的幻觉怎么产生？怎么检测和修复？",
'''【L1·回答】
RAG幻觉原因：①检索失败(没找到相关信息→模型被迫编造)；②生成模型忽略上下文(过度依赖自身知识)；③上下文矛盾(多文档信息冲突→模型选错)。检测：Faithfulness指标。

【L2追问】检索失败vs生成忽略上下文，怎么区分？
【L2·回答】
对比分析：①检查检索结果——检索到了但答案没用到→生成模型问题(忽略上下文)；②检索结果就没有相关信息→检索问题。三个指标联合诊断：Context Recall低=检索问题，Context Precision低=检索了但噪声多，Faithfulness低=生成了不支持信息。

【L3追问】怎么修复"模型忽略上下文"的问题？
【L3·回答】
①Prompt优化——强调"只根据提供的上下文回答，不要使用外部知识"；②增加Context Recall惩罚；③Fine-tuning——用"强制引用"训练数据微调；④Post-hoc检测——检测答案中的事实是否在上下文中出现。

【L4追问】如果检索到了相关信息但模型用错了(张冠李戴)，怎么处理？
【L4·回答】
这是最棘手的RAG幻觉——不是没检索到，也不是完全忽略，而是用错了。检测：claim级别的细粒度验证(每个claim和每个检索文档逐条比对)。修复：①增强Prompt——要求模型"逐条引用"每个事实的来源；②用更强调的引用格式(如"根据文档A第3段...")；③后处理——用NLI(自然语言推理)模型逐claim验证。''')

qa("Q45. RAG评测的自动化流水线怎么设计？门禁阈值怎么设定？",
'''【L1·回答】
流水线：触发→数据准备→执行(遍历Query→调RAG→收集结果)→评测(RAGAS+自定义指标)→报告(Grafana/PDF/企微推送)→门禁(指标低于阈值→CI Failed)。

【L2追问】门禁阈值的设定逻辑？
【L2·回答】
分级：①安全相关(Faithfulness)→严格(>0.9)，低于则Block；②体验相关(Relevancy)→宽松(>0.8)，低于则Warning；③新功能→比baseline下降>5%则Block；④整体质量→综合分数低于阈值Block。阈值需和业务方对齐+定期review。

【L3追问】如果门禁误报(指标下降是波动而非真退化)怎么办？
【L3·回答】
①多次评测取平均——跑3次取均值+标准差；②统计检验——Welch's t-test判断差异是否显著(p<0.05)；③人工复核——被Block变更由人工抽检；④历史基线——对比过去7天趋势，看是否在正常波动范围。关键是降低误报率同时不漏真问题。

【L4追问】怎么设计"综合分数"来整合多个指标？
【L4·回答】
加权求和：综合分=w1·Faithfulness+w2·Relevancy+w3·ContextPrecision+w4·ContextRecall。权重由业务方确认(安全场景w1高，客服场景w2高)。也可用乘法(短板效应)：综合分=Faithfulness×Relevancy×Precision×Recall——任一个低都会拉低总分。选择取决于是否允许"指标间补偿"。''')

