section("第5章 模型性能与推理优化（Q61-Q70）")

qa("Q61. 推理性能核心指标？TTFT和TPOT分别指什么？",
'''【L1·回答】
核心指标：TTFT(Time To First Token)——首Token延迟，影响用户感知；TPOT(Time Per Output Token)——每Token间隔，影响流畅度；Throughput(吞吐量)；Latency P50/P95/P99。

【L2追问】TTFT和TPOT的优化方向分别是什么？
【L2·回答】
TTFT优化：①Prefill阶段优化(Flash Attention/量化KV Cache)；②模型加载速度；③调度策略。TPOT优化：①KV Cache命中率；②Decode阶段优化(Continuous Batching/Speculative Decoding)；③采样简化。TTFT是冷启动问题，TPOT是稳态问题。

【L3追问】Speculative Decoding是什么？怎么加速TPOT？
【L3·回答】
用小模型(草稿模型)快速生成K个候选Token→大模型一次性验证K个→接受正确的→加速K倍(理想)。原理：大模型验证K个Token和生成1个Token计算量相同。关键：草稿模型的"猜测准确率"决定加速比。

【L4追问】Speculative Decoding的实际加速比？有什么局限？
【L4·回答】
实际加速：1.5-3x(取决于草稿模型质量和任务类型)。局限：①草稿模型需额外显存；②草稿模型和大模型的Tokenizer需兼容；③对话/创意任务(高熵)加速比低(猜不准)，代码/翻译(低熵)加速比高。vLLM和TGI都支持此特性。''')

qa("Q62. Continuous Batching vs Static Batching？",
'''【L1·回答】
Static Batching：一批请求同时到达→同时处理→等最慢的。Continuous Batching：请求动态加入和离开，不等待。vLLM的核心吞吐优化。

【L2追问】Continuous Batching的实现难点？
【L2·回答】
①KV Cache动态管理——请求加入/离开时需分配/释放(内存碎片)；②调度策略——何时加入新请求(不能等太久也不能太频繁)；③注意力掩码——不同长度请求的因果掩码不同，需高效构造。vLLM用PagedAttention解决KV Cache碎片。

【L3追问】PagedAttention怎么配合Continuous Batching？
【L3·回答】
PagedAttention将KV Cache分成固定大小page→按需分配→请求加入分配新page→离开释放→page可复用。类比OS虚拟内存：请求=进程，page=物理页框，页表=KV Cache映射。两个技术的协同优化。

【L4追问】调度策略(Scheduling Policy)有哪些？怎么选？
【L4·回答】
FCFS(先到先服务)、Priority(按优先级)、Preemption(抢占)。vLLM支持抢占：高优请求到达→低优请求KV Cache从GPU→CPU(Swap)或直接丢弃(Recompute)。选择：实时场景用Priority+Preemption，批量场景用FCFS。评测场景请求长度相近，FCFS够用。''')

qa("Q63. 模型推理的显存都花在哪了？量化省多少？",
'''【L1·回答】
三部分：①模型权重(FP16: 2×参数量，7B=14GB)；②KV Cache(2×层数×KV头数×维度×长度×2字节)；③激活值(中间计算结果)。

【L2追问】量化(INT8/INT4)分别省多少？
【L2·回答】
INT8：权重14GB→7GB(省50%)。INT4：14GB→3.5GB(省75%)。KV Cache通常不量化，激活值可选量化。总省：INT8约40%，INT4约60%。QLoRA用4bit权重+FP16 KV Cache→65B模型可在48GB GPU微调。

【L3追问】为什么KV Cache一般不量化？
【L3·回答】
KV Cache量化显著影响注意力质量——注意力计算涉及大量乘加，量化误差在softmax中被放大。有研究(KVQuant/KIVI)在做KV Cache量化，但未成标准。当前主流：权重量化+KV Cache保持FP16。

【L4追问】怎么测试量化后的精度损失？
【L4·回答】
①基准测试(Benchmark)——MMLU/HellaSwag等标准基准对比；②Perplexity——同数据集PPL对比；③下游任务——实际业务场景的端到端指标对比；④长文本——量化对长序列影响更大(累积误差)。损失<2%通常可接受。关键是"业务可接受"而非"技术完美"。''')

qa("Q64. 模型冷启动问题怎么测试和优化？",
'''【L1·回答】
冷启动：模型加载到GPU→预热→可服务。问题：加载时间(几秒到几分钟)、预热请求高延迟、KV Cache为空。测试：记录从启动到稳态性能的时间。

【L2追问】怎么减少冷启动影响？
【L2·回答】
①预热请求——启动后自动发预热请求(填充KV Cache+触发JIT编译)；②模型常驻——不频繁重启；③分层加载——先加载核心层快速响应→后台加载全部；④快照恢复——保存预热后状态，重启直接加载。

【L3追问】预热请求发什么内容？怎么设计预热策略？
【L3·回答】
预热内容：①代表性请求——覆盖不同长度/类型；②梯度递增——先短后长(短请求快速预热+长请求充分预热)；③监控预热效果——预热前后TTFT对比，直到TTFT稳定(波动<10%)。

【L4追问】vLLM/TGI的预热最佳实践？
【L4·回答】
vLLM：启动后自动做CUDA kernel预热(JIT编译)，但KV Cache为空→前几个请求延迟高。最佳实践：部署后先发10-20个预热请求(不同长度)，观察TTFT稳定后再接入流量。TGI：支持--warmup参数自动预热。生产环境必须在接入流量前完成预热。''')

qa("Q65. 多模型路由的性能怎么测试？路由决策怎么做？",
'''【L1·回答】
多模型路由：根据请求特征选不同模型(GPT-4处理复杂推理，GPT-4o-mini处理简单对话)。测试：路由准确率、路由延迟、整体性能。

【L2追问】路由决策用什么特征？
【L2·回答】
特征：①Query复杂度(长度/推理关键词/历史轮次)；②用户优先级(VIP用强模型)；③预算约束(月度预算剩余)；④延迟要求(实时用小模型)。决策：规则引擎→ML分类器→LLM自判断。

【L3追问】路由错了怎么办？小模型答不好→怎么fallback？
【L3·回答】
①答案质量检测——小模型输出后用Judge快速评估→不合格升级大模型；②超时fallback——小模型超时→切大模型；③用户反馈——点"不满意"→自动用大模型重新生成。监控路由质量：正确路由率+升级率+用户满意度。

【L4追问】怎么量化路由策略的ROI？
【L4·回答】
ROI=(成本节省-路由开销)/成本节省。成本节省=大模型成本×(1-路由到小模型比例)×(大模型单价-小模型单价)。路由开销=路由决策延迟+误路由损失(该用大模型但用了小模型→用户不满→重试成本)。最佳路由比例需通过A/B实验确定。''')

