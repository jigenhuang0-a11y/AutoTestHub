Q("Q16. 简单介绍一下Transformer的基本结构？",
"""【L1·回答】
Transformer = Encoder（编码器）+ Decoder（解码器）
核心组件：
① Self-Attention（自注意力）——让每个词看到句子中所有词，计算相关性
② Feed Forward Network（前馈网络）——对每个词做非线性变换
③ Layer Normalization（层归一化）——稳定训练
④ 残差连接（Residual Connection）——防止梯度消失

工作流程：
输入 → Embedding → 位置编码 → 多层Transformer Block → 输出

现代LLM（GPT系列）只用Decoder部分（自回归生成）。

【L2追问】Self-Attention为什么有效？
【L2·回答】
三个原因：
① 全局视野——每个Token能直接看到序列中所有Token，不像RNN要逐步传递
② 动态权重——注意力权重由输入内容决定，不是固定的。"apple"在"吃苹果"和"苹果公司"中关注不同的上下文
③ 并行计算——所有Token的注意力可以同时计算（矩阵乘法），不像RNN必须串行

直观理解：Self-Attention就是让模型学会"理解这个词时，应该参考哪些其他词"。""")

Q("Q17. 什么是Token？Tokenization怎么做？",
"""【L1·回答】
Token = LLM处理文本的最小单位，不是字也不是词。
- 英文：1个Token ≈ 0.75个单词（"apple"=1 Token，"eating"可能是2个Token）
- 中文：1个Token ≈ 0.5-1.5个汉字（取决于分词方式）

Tokenization方法：
① BPE（Byte Pair Encoding）——GPT系列使用，从字符开始逐步合并高频组合
② WordPiece——BERT使用
③ SentencePiece——LLaMA使用

【L2追问】为什么Tokenization对AI测试很重要？
【L2·回答】
三个原因：
① Token限制——LLM有上下文窗口限制（如4K/8K/128K Token），测试时需要确保输入不超过限制
② Token计数——评测成本按Token计费，需要控制测试用例的Token消耗
③ 分词差异——同一个词在不同模型中的分词方式不同，导致相同文本的Token数不同
  - 例如中文在GPT中可能比在LLaMA中Token数更多
  - 测试时需要统一按Token计数而非字符数来设计测试用例

实践：在AutoTestHub中记录每条case的Token消耗，方便成本核算和超限检测。""")

Q("Q18. Prompt是什么？好的Prompt有什么特征？",
"""【L1·回答】
Prompt = 给LLM的指令，决定LLM的输出行为和质量。
好的Prompt特征：
① 角色明确——告诉LLM它是什么角色（"你是一个AI测试专家"）
② 任务清晰——具体要做什么（不是"写点东西"，而是"写200字的XX介绍，包含A/B/C三点"）
③ 约束具体——格式要求、禁止事项、输出结构
④ 示例引导（Few-shot）——给1-3个期望的输入输出示例
⑤ 思维链——让LLM"一步步思考"，提高推理准确率

【L2追问】你怎么优化一个效果不好的Prompt？
【L2·回答】
优化流程：
① 分析badcase——收集输出不符合预期的case，分类归纳问题模式
② 定位问题——是指令不清晰、缺少约束、还是示例不足？
③ 迭代修改——每次只改一个变量，对比修改前后的效果
④ A/B Test——新旧Prompt各跑50条，对比指标
⑤ 重复直到满意——通常需要3-5轮迭代

常见问题及修复：
- 输出太长 → 加字数限制
- 输出格式乱 → 指定JSON/Markdown格式
- 幻觉（编造信息） → 加"不知道就说不知道"
- 回答太泛 → 加"请具体说明，给出例子" """)

Q("Q19. 什么是幻觉（Hallucination）？怎么检测和减少？",
"""【L1·回答】
幻觉 = LLM生成的看似合理但实际不真实/不存在的内容。
类型：
① 事实幻觉——编造不存在的事实、人名、数据
② 来源幻觉——编造不存在的论文、引用
③ 逻辑幻觉——推理过程看似合理但结论错误

检测方法：
① 事实核查——用搜索引擎/知识库验证LLM输出中的事实陈述
② 一致性检查——同一问题多次询问，回答是否一致
③ 置信度评估——让LLM自己评估回答的可信度

减少方法：
① RAG——先检索真实文档，再基于文档生成
② Prompt约束——"如果不知道，请明确说不知道"
③ 引用要求——要求LLM给出信息来源

【L2追问】在测试中怎么量化幻觉程度？
【L2·回答】
量化指标：
① 幻觉率 = 包含虚假信息的回答数 / 总回答数
② 幻觉严重度——轻微（小细节错误）/ 中等（关键信息错误）/ 严重（完全编造）
③ Faithfulness分数——用RAGAS的Faithfulness指标，逐条验证回答中的断言

测试方法：
- 准备"可验证"的测试集（问题有明确正确答案）
- 让LLM回答 → 逐条核查事实正确性
- 按领域统计幻觉率（历史/科学/常识通常更高）

AutoTestHub中：Faithfulness < 3.0/5.0 标记为"可能存在幻觉"，需人工复核。""")

Q("Q20. 什么是RAG？为什么需要RAG？",
"""【L1·回答】
RAG = Retrieval-Augmented Generation（检索增强生成）
流程：用户Query → 检索相关文档 → 把文档+Query一起给LLM → LLM基于文档生成回答

为什么需要：
① 减少幻觉——LLM基于真实文档回答，而非纯靠记忆
② 知识更新——不需要重新训练模型，更新文档即可
③ 可溯源——回答可以标注信息来源
④ 领域知识——通用LLM不懂的专业领域知识，通过检索外部文档补充

典型场景：企业知识库问答、产品说明书问答、客服系统。

【L2追问】RAG有哪些常见问题？
【L2·回答】
四大常见问题：
① 检索失败——没找到相关文档 → LLM凭记忆回答（可能编造）
② 检索噪声——找到不相关文档 → LLM被误导
③ 上下文窗口溢出——检索到的文档太多 → 超出Token限制，信息截断
④ 引用错误——LLM引用了不存在的文档内容

测试重点：
- 检索质量（Recall/Precision）
- 生成忠实度（Faithfulness）
- 引用准确性（引用的内容是否确实在文档中）

这些问题在AutoTestHub的评测指标中都有对应检测维度。""")

