Q("Q6. AI测试和传统软件测试有什么区别？",
"""【L1·回答】
三大核心区别：
① 输出非确定性——传统测试输入A→输出B，可精确断言；AI测试同一输入输出不同，需统计断言
② 质量多维模糊——传统测试Pass/Fail二元判断；AI测试需多维度打分（准确性/安全性/体验）
③ 评测本身是AI——传统测试用固定规则验证；AI测试用LLM做Judge，Judge本身需要校准

【L2追问】传统测试的哪些经验可以迁移到AI测试？
【L2·回答】
可迁移的：
① 测试分层思想——AI测试也分层：Prompt单元测试→RAG集成测试→端到端测试
② 边界值分析——AI输入也有边界（超长文本/空输入/特殊字符/多语言）
③ 回归测试——Prompt/模型变更后自动跑测试集对比指标
④ 等价类划分——按Query类型分组测试（事实查询/推理/创意/代码）

不可直接迁移的：
① 精确断言→统计断言
② 固定测试数据→需持续更新的标注数据集
③ 自动化脚本→AI辅助的评测引擎""")

Q("Q7. 你怎么设计AI测试用例？和传统测试用例有什么区别？",
"""【L1·回答】
AI测试用例设计方法：
① 场景分类——按业务场景分类（客服问答/内容生成/代码辅助/安全检测）
② 难度分级——简单（直接匹配）/ 中等（需推理）/ 困难（需多步推理或专业知识）
③ 边界case——空输入、超长输入、特殊字符、多语言混合、歧义输入
④ 对抗case——故意诱导LLM犯错的输入（陷阱问题、矛盾前提）

和传统测试用例的区别：
- 传统：输入+预期输出+断言逻辑，是确定性的
- AI：输入+评测标准+容忍度，是概率性的。不是"对不对"，是"好不好+多稳定"

【L2追问】怎么保证测试用例的覆盖率？
【L2·回答】
用覆盖矩阵：
① 维度覆盖——功能正确性/安全性/鲁棒性/性能/体验，每个维度至少20条case
② 场景覆盖——按业务场景分类，确保核心场景全覆盖
③ 难度覆盖——简单40%/中等40%/困难20%
④ 输入类型覆盖——短文本/长文本/多轮对话/含上下文/含约束条件

每周review覆盖率报告，发现盲区及时补充。目标是核心场景100%覆盖，边缘场景80%覆盖。""")

