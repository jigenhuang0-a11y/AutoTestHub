Q("Q17. 介绍一下RAGAS框架，它的核心指标是什么？你在项目中怎么用的？",
"""【L1·回答】
RAGAS是一个专门评测RAG系统的开源框架，提供四个核心指标：

① Faithfulness（忠实度）——生成的答案中有多少声明可以从检索到的上下文中验证。核心公式：可验证声明数 / 总声明数
② Answer Relevancy（答案相关性）——答案是否紧密回应用户问题，有没有偏离
③ Context Precision（上下文精确度）——检索到的文档中，相关的占多少。衡量检索质量
④ Context Recall（上下文召回率）——应该检索到的文档，实际检索到多少

在AutoTestHub中，我参考了RAGAS的指标设计，但没有直接集成（因为券方式接入的局限）。如果现在重构，会以RAGAS为基础+自定义扩展。

【L2追问】RAGAS的Faithfulness计算逻辑是什么？有什么局限？
【L2·回答】
计算逻辑：
① 用LLM从生成的答案中提取所有"声明（Claims）"
② 对每条声明，判断是否能从检索上下文中验证
③ Faithfulness = 可验证声明数 / 总声明数

局限：
① Claim提取依赖LLM，同样存在偏差——LLM可能漏掉某些声明
② 只看"有没有依据"，不看"依据对不对"——可以验证≠正确
③ 对长文档可能误判——一条声明可能分布在多个chunk中，LLM可能漏判

补充做法：在Faithfulness之外，加一个"事实准确率"人工抽检，用真实世界知识验证关键声明的正确性。RAGAS是好工具，但不能盲信。""")

Q("Q18. RAG系统的'幻觉（Hallucination）'和纯LLM的幻觉有什么不同？怎么测？",
"""【L1·回答】
纯LLM幻觉：模型凭空编造信息。比如问"某明星的生日"，模型编一个日期。

RAG幻觉：更狡猾——分为两类：
① 无视上下文型——检索到了正确信息，但生成的答案不采用，自己编了一个
② 上下文误读型——检索到的信息是对的，但理解错了，输出偏离原文意思

评测方法：
① 声明级验证——把答案拆成一条条声明，逐条和检索上下文比对
② 关键信息提取——提取答案中的数字、人名、日期等关键信息，和原文比对
③ 矛盾检测——检查答案是否和检索上下文中的任何信息矛盾

【L2追问】RAG系统最容易在什么情况下产生幻觉？
【L2·回答】
三个高危场景：
① 检索失败——没找到相关文档，LLM强行回答（最典型场景）。解决方案：检索结果为空时应该回复"我不知道"，而不是硬编
② 上下文矛盾——检索到多篇文档，但内容互相矛盾，LLM随便选了一个。解决方案：检查文档间一致性，矛盾时标注不确定性
③ 低质量上下文——检索到的内容本身错误，LLM基于错误信息生成答案（Garbage In Garbage Out）。解决方案：对检索源做质量控制

关键设计：RAG系统必须有"我不确定"的输出通道，不能强迫LLM在所有情况下都给出信心满满的答案。""")

Q("Q19. Chunk Size（文档分块大小）对RAG评测结果有多大影响？你怎么确定最优Chunk Size？",
"""【L1·回答】
Chunk Size是RAG系统最容易被忽略但影响很大的参数。

影响机制：
- 太小的Chunk（如128 tokens）：语义碎片化，检索时可能丢失上下文，但精确度高
- 太大的Chunk（如1024 tokens）：包含更多上下文，但检索时噪声多，精确度低
- 最优值：通常在256-512之间，取决于文档类型

评测方法：
在固定数据集上，用不同Chunk Size跑RAG评测：
- Chunk=128 → 记录Context Precision和Recall
- Chunk=256 → 同上
- Chunk=512 → 同上
- Chunk=1024 → 同上
找到Precision×Recall最大的那个Chunk Size。

【L2追问】除了Chunk Size，还有哪些影响检索质量的因素？
【L2·回答】
四个关键因素，按影响大小排序：
① Embedding模型——不同的模型对同一文本的向量表示不同，直接影响检索质量。需要做Embedding模型对比评测
② 检索策略——是只用向量检索，还是混合检索（向量+关键词）？混合检索通常更好
③ Rerank——检索后是否做重排序？加一个Rerank模型可以大幅提升Precision
④ Chunk重叠（Overlap）——相邻Chunk之间保留多少重叠字符。太小可能切掉关键信息，太大增加冗余

这些都是可量化的——可以通过Context Precision和Recall的对比来验证每个参数的效果。""")

Q("Q20. 你怎么构建RAG系统的测试数据集？",
"""【L1·回答】
RAG测试数据集比纯LLM测试数据集复杂，因为多了检索部分。

构建步骤：
① 构建文档库——真实业务文档（或代表性的模拟文档），确保覆盖多领域、多难度
② 设计问题——针对每份文档设计问题，分三类：
  - 简单查找型："文档中某参数的值是多少"（直接检索能回答）
  - 推理型："综合文档内容，分析某某原因"（需要跨段落理解）
  - 边界型："文档中没有提到的内容"（测试"我不知道"场景）
③ 标注预期——对每个问题标注：正确答案、应检索到的文档ID、可接受的答案范围

关键设计：必须包含"文档中没有答案"的问题——测试RAG系统是否诚实。

【L2追问】测试数据集的质量怎么保证？
【L2·回答】
① 双人交叉验证——问题设计者和答案标注者不是同一个人
② 难度分层——确保简单/中等/困难各占1/3，避免评测结果偏向某一难度
③ 定期更新——文档库变化后，数据集也要同步更新
④ 覆盖度检查——检查每份文档是否都被至少一个问题覆盖，避免盲区

RAG测试最大的坑：测试集的问题都能在文档库中找到答案。这会导致评测过于乐观——真实用户问的问题，很大概率文档库里没有。""")

Q("Q21. 如果RAG系统检索到了不相关或有害的内容，但LLM正确地拒绝了使用它，这个算Pass还是Fail？",
"""【L1·回答】
算Pass——用分阶段评估。

核心思想：把RAG的检索和生成分开评估。

① 检索阶段：检索到了不相关内容 → 检索质量扣分（Context Precision下降）
② 生成阶段：LLM拒绝了不相关内容，给出了安全回复 → 生成质量加分（安全性+Faithfulness OK）

所以整体是：检索环节有瑕疵，但生成环节表现好，最终系统输出是安全的 → Pass。

但这个问题暴露了检索质量的问题——需要排查为什么检索到了不相关内容（Embedding模型问题？文档质量问题？）。

【L2追问】这引出了一个问题：到底谁的评测更重要？检索还是生成？
【L2·回答】
对用户来说，最终输出最重要——所以生成评测优先级更高。

但对系统优化来说，检索评测更重要——检索是源头，源头不好，生成再好也有限。

实际做法：
① 对外（给产品和Leader看）：看最终输出质量（Faithfulness + Answer Relevancy）
② 对内（给技术团队优化用）：看检索质量（Context Precision + Recall）和生成质量拆开看

把两个混在一起，就会出现"整体分数还行，但不知道优化哪里"的问题。拆分评测才能指导行动。""")

Q("Q22. 多轮对话场景下的RAG评测怎么做？",
"""【L1·回答】
多轮对话和单轮RAG评测的关键区别：第二轮及以后的回答，不仅依赖当前检索结果，还依赖历史对话上下文。

评测难点：
① Faithfulness需要验证答案是否同时忠于上下文+历史对话
② 对话历史中的错误会累积——第一轮的微小偏差可能导致第三轮完全离题
③ 评测成本高——多轮对话的标注工作量是指数级的

我的做法：
① 设计多轮对话测试场景——每轮设计用户问题和预期回答方向（不要求逐字匹配）
② 逐轮评测——每轮独立打分，同时看累积效果
③ 关键轮次重点评测——第1、3、5轮重点评测（奇数轮往往是话题转折点）

【L2追问】对话历史中的错误怎么定位？
【L2·回答】
用"回溯法"：
① 发现第N轮答案有问题 → 回溯检查第N轮的检索结果
② 检索结果没问题 → 回溯检查第N-1轮的对话历史，看是否被前一轮的错误引导了
③ 如果第N-1轮也有问题 → 继续回溯，直到找到源头

这就像debug一个链式调用——错误可能在链条的任何一环，需要逐环排查。""")

