S("第8章 评测数据集与标注管理——评测质量的基石")

Q("Q42. 你怎么构建一个高质量的AI评测数据集？",
"""【L1·回答】
黄金法则：Garbage In, Garbage Out。评测数据集质量差 → 评测结果没有意义。

构建步骤：
① 场景覆盖——从真实用户问题中抽样，确保覆盖高频场景和长尾场景
② 难度分层——简单/中等/困难各占1/3，避免评测结果偏向某一难度
③ 类型多样化——事实类/推理类/创作类/边界类，每类至少30条
④ 标注质量控制——三人交叉标注，分歧case讨论解决
⑤ 定期更新——每季度review，淘汰过时case，补充新场景

规模建议：初始版本100-200条，逐步扩展到500-1000条。

【L2追问】为什么一定要分层？不能随机抽吗？
【L2·回答】
随机抽会导致评测结果不可靠的例子：
- 如果90%的随机样本都是简单问题 → 评测结果会高估模型能力
- 如果90%都是困难问题 → 评测结果会低估模型能力
- Leader看报告说"模型能力很好/很差"，但实际只是样本偏差

分层抽样确保评测结果反映的是真实能力分布，不是样本偏差。这是基础统计学概念，但在评测实践中常被忽略。""")

Q("Q43. 标注质量怎么保证？你遇到过'标注比想象中难'的情况吗？",
"""【L1·回答】
标注比写代码难——代码有编译器和测试验证，标注只有人。

质量控制四层：
① 标注指南——每个维度有具体的打分标准+正反面例子（不是"打1-5分"就完事）
② 双人标注——同一case至少2人独立打分，计算一致性
③ 分歧处理——2人打分差>1分 → 第三人仲裁；差≤1分 → 取平均
④ 一致性监控——标注员间的Cohen's Kappa<0.6 → 需要重新培训

最难的标注场景：安全/有害内容判断——同一句话"A和B吵起来了"，有人觉得是描述、有人觉得是暴力内容。

【L2追问】标注成本太高怎么办？
【L2·回答】
分两层：
① 核心评测集（用于验证评测方法本身）——必须高质量人工标注，不可压缩
② 日常评测集（用于批量跑分）——可以用LLM辅助标注+人工抽检

核心评测集只需要200条就够，维护好它的质量。日常评测集可以用LLM生成+LLM标注+人工抽检10%。

好钢用在刀刃上——Golden Dataset是刀刃，值得花时间做精。""")

Q("Q44. 评测数据集的'保质期'有多久？什么时候需要更新？",
"""【L1·回答】
评测数据集是易腐品，不是永久资产。

更新触发条件：
① 模型能力变化——LLM能力提升后，原来难的问题变简单了 → 评测集区分度下降
② 产品功能变化——加了新功能（如文档上传），需要补充新场景的评测case
③ 评测标准变化——业务重点变了（如从'准确性优先'变成'安全性优先'），需要重新标注权重
④ 发现盲区——线上出了评测集完全覆盖不到的bug类型

维护频率：每季度review一次。淘汰不具区分度的case（两个模型都能答对的），补充新场景case。

【L2追问】不更新会有什么后果？
【L2·回答】
评测分数通胀——随着模型进步，所有模型的得分都在涨，但评测没有变难。半年后：
- 去年GPT-3.5评测得0.75
- 今年GPT-4评测得0.92
- 看起来进步巨大，但其实评测集已经过时了（去年难的问题今年都变简单了）

评测集过时的典型信号：top模型和baseline模型的差距越来越小 → 不是模型差距小了，是评测集区分度不够了。

评测集是标尺。标尺本身不更新，测量出来的'进步'就是假象。""")

Q("Q45. 你怎么管理评测数据的版本？",
"""【L1·回答】
评测数据版本管理三个维度：

① 数据集版本——每次增删改case都打version tag（v1.0→v1.1→v2.0）
② 评测结果版本——每次跑评测的结果存档，关联数据集版本+模型版本+评测方法版本
③ 评测方法版本——评测Prompt改了也要记录

核心原则：可复现。任何人随时可以拿历史数据重新跑评测，得到相同结果。

实现方式：用Git管理评测Prompt和数据集文件，用数据库（SQLite/PostgreSQL）存评测结果。

【L2追问】版本号打架怎么办？不同团队同时改了评测集。
【L2·回答】
Git解决——每个变更是一个PR，合并后自动打tag。
大版本号变更规则：数据集增删>20% → 主版本号+1；增删<20% → 副版本号+1。
团队要约定好版本号规则，不然两个月后没人知道v2.3和v1.8哪个更新。

在AutoTestHub中，每次评测都记录了dataset_version字段，方便回溯时确认用的是哪个版本的数据集。""")

