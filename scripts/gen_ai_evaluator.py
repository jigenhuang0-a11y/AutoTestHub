Q("Q4. LLM输出是非确定性的——同一输入可能得到不同答案。你怎么设计评测来应对这个问题？",
"""【L1·回答】
这是AI测试和传统测试最根本的区别。传统测试：输入A→预期输出B→断言A==B。AI测试做不到这样。

我的三层策略：
① 统计断言代替精确断言——不看"这次对不对"，看"100次里多少次达标"。Faithfulness均值≥0.85且标准差<0.05才算通过
② 多次评测取稳定结果——每条测试跑3-5次，取中位数或均值，避免单次波动误判
③ 容忍区间设计——不同任务类型不同标准：
  - 事实类任务（技术问答）：严格要求，波动阈值<0.2
  - 创意类任务（文案生成）：宽松标准，波动阈值<0.5

【L2追问】如果某个case连续3次评测分数分别是3/5/2，你怎么处理？
【L2·回答】
这种情况说明评测本身可能有问题，不是模型的问题：
① 先看Judge的一致性——如果标准差=1.25，远超正常范围（通常<0.3），说明评测Prompt可能不够清晰，Judge在"乱打"
② 人工评审——随机抽这条case让人工打分，和Judge的对标，找出偏差原因
③ 优化评测Prompt——如果人工判定是4分，但Judge打了3分，说明评测维度描述不够精确，需要细化
④ 标记为"不稳定类"——如果优化后仍波动大，说明这类case本身就是歧义的，应该从自动化评测中剔除，走人工审核通道

核心原则：不要盲目信Judge。Judge本身也是LLM，也有偏差和随机性。""")

Q("Q5. AutoTestHub中的'AI测评师'模块是怎么实现的？",
"""【L1·回答】
AI测评师本质上是一个评测Agent，工作流程：
① 接收评测任务（被测LLM的输出 + 评测标准）
② 调用LLM（Judge）进行多维度打分
③ 汇总分数 → 生成评测报告
④ 如果打分置信度低（不同维度矛盾或多次评分波动大）→ 触发人工复核

实现上用的是Prompt Engineering + 结构化输出：
- 设计评测Prompt模板（含评测维度、打分标准、输出格式）
- LLM按模板输出JSON格式的评分结果（每个维度一个分数+理由）
- 后端解析JSON → 存入数据库 → 看板展示

【L2追问】怎么保证Judge打分的准确性和一致性？
【L2·回答】
四层校验：
① 低Temperature控制——评测时用Temperature=0.1，减少随机性，让Judge打分更稳定
② 人工对标校准——每月抽样100条人工打分，计算与Judge的Cohen's Kappa，目标>0.7
③ 交叉验证——关键评测用两个不同模型（如GPT-4+Claude）分别打分，分数差异>0.2时触发人工复核
④ 评测维度细化——不让Judge打一个笼统的"质量分"，拆成准确性/完整性/安全性三个子维度分别打分，每个维度给出具体理由

效果：人工对标Kappa达到0.72-0.78，说明Judge和人类判断高度一致。""")

Q("Q6. 你在做AutoTestHub的过程中遇到的最大技术挑战是什么？怎么解决的？",
"""【L1·回答】
最大挑战是"评测的可靠性验证"——你怎么知道Judge打得对不对？

这本质是个元评测问题：用LLM评测LLM，谁来评测这个评测过程？

我的解决思路：
① 构建标准评测集——人工标注50条高质量评测样本（每个sample有人工打分+理由）
② 用标准集验证Judge——Judge在标准集上的打分和人工打分对比，计算MAE（平均绝对误差）
③ MAE>0.5 → 优化评测Prompt → 重新验证 → 直到MAE<0.3
④ 持续监控——每次改评测Prompt后，重新跑标准集验证，防止退化

【L2追问】标准评测集怎么保证质量？
【L2·回答】
① 三人交叉标注——每条样本由3个不同的人打分，取中位数
② 分歧处理——如果3人打分标准差>0.5，四人讨论达成共识
③ 定期轮换——标准集会过时（LLM能力提升后，原来的"好答案"可能变成"一般"），每季度review一次

这个思路来自传统测试的Golden Dataset概念——没有Golden Dataset，你就不知道你的测试工具本身是否正确。""")

