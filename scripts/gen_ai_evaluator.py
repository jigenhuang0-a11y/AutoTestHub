Q("Q46. 你怎么把AI评测集成到CI/CD流水线中？",
"""【L1·回答】
评测CI/CD流水线设计：

触发 → 执行 → 评判 → 决策

① 触发条件：每次模型更新/Prompt变更/训练数据变更 → 自动触发评测流水线
② 执行：拉取最新模型配置 → 批量跑评测集（200+条） → 计算所有指标
③ 评判：对比基线（当前生产版本指标） → 判断是否偏离超过阈值
④ 决策：
  - 全部通过 → 自动放行
  - 有指标告警（偏离1-2个标准差） → 通知团队但不阻断
  - 有指标阻断（偏离>2个标准差或安全指标低于阈值） → 阻断发版

【L2追问】评测流水线的执行时间太长怎么办？每次跑200条要10分钟。
【L2·回答】
分层执行：
① 快速门禁（1分钟内）——跑30条高优先级case（安全case+核心场景case），先做快速判断
② 完整评测（后台异步）——剩下的170条后台跑，不阻塞发版流水线
③ 如果快速门禁通过但完整评测发现问题 → 发版后再回滚/修复（极小概率事件）

像消防通道——不能因为要全面检查就堵住出口。快速门禁保底线，完整评测保全面。""")

Q("Q47. 评测结果出现异常波动，你怎么排查？",
"""【L1·回答】
异常波动的排查SOP：

① 确认异常——是某个指标异常还是全面下降？单一指标异常通常指向特定问题
② 查变更——最近改了什么？模型更新？Prompt修改？测试集更新？
③ 场景拆解——按任务类型拆开看，是全部类型都下降还是特定类型？
④ 抽样对比——抽10条分数下降最多的case，人工看新旧版本的回答差异
⑤ 根因定位——是模型变差了？评测Prompt不合适？还是测试集有问题？

常见原因：
- Prompt变更 → 通常影响特定场景
- 模型更新 → 通常影响多个指标
- 测试集更新 → 新旧版本不可直接对比，需要重新建基线
- Judge模型变更 → 评分整体偏移（系统性偏差）

【L2追问】如果排查后还是找不到原因怎么办？
【L2·回答】
先标记，不阻断：
① 标记为"未知异常"——这次发版不阻断，但设置监控（下次发版如果同样异常 → 必然有问题）
② 扩大样本——原来抽10条对比，扩大到30条
③ 找人帮忙——拉算法同学一起看，可能是我对模型行为不够了解

承认"我不知道"比硬给一个错误解释更专业。但也必须设置后续跟进机制——不能"不知道"就结束了。""")

Q("Q48. 你怎么监控评测体系本身的健康度？",
"""【L1·回答】
评测体系也需要被评测。

健康度监控维度：
① 评测一致性——Judge每周跑Golden Dataset，Kappa是否有退化？
② 评测稳定性——同一批case连续跑3天，分数波动是否在±0.03内？
③ 评测覆盖度——评测集是否覆盖了线上出现问题最多的场景？线上bug和评测集覆盖度对比
④ 评测时效性——评测结果出来后到被采纳的间隔多久？如果没人看 → 评测体系本身出了问题

关键指标：Golden Dataset Pass Rate——每月一次，Judge在Golden Dataset上的打标准确率。如果从85%降到78% → 评测体系健康度在下降，需要排查。

【L2追问】评测体系出问题，比被测系统出问题更难发现？
【L2·回答】
对。因为：
- 被测系统出问题 → 评测分数下降 → 能感知到
- 评测体系出问题 → 评测分数可能不变或异常变化 → 不容易感知（你不知道是模型真变好了还是评测变松了）

这就是为什么Golden Dataset的定期验证是必须的——它是评测体系的"体检报告"。
一个不监控自身健康度的评测体系，半年后给出的分数可能完全没有参考价值。""")

Q("Q49. 如果让你给团队介绍'什么是好的AI评测实践'，你会讲哪三个要点？",
"""【L1·回答】
三个要点，按重要性：

① 可对标——评测结果必须能和某种参照物对比验证。
  没有Golden Dataset的评测不是评测，是算命。
  至少要有人工抽检校准，知道你的评测方法的"准确率"边界在哪。

② 可行动——评测结果能直接指导优化方向。
  不只是"分数低"，而是"分数低是因为某类问题处理不好，建议优化某部分Prompt/检索策略"。
  不能指导行动的评测报告 = 垃圾信息。

③ 可持续——评测体系能随着产品和模型演进。
  不是一次性项目——评测集要更新、评测方法要校准、门禁要调整。
  一个三年前的评测集用在今天的模型上，出来的分数参考价值极低。

【L2追问】这三条哪条最难做到？
【L2·回答】
第三条——可持续最难。
因为可对标和可行动是技术问题，可持续是组织问题。
需要：持续的人力投入、Leader的长期支持、团队对评测价值的认可。
很多团队的评测体系第一版做得很好，半年后因为没人维护就废了。

我的经验：把评测维护成本压缩到最低（自动化Golden Dataset验证、自动化评分异常检测），让人力投入不是"维护评测系统"，而是"使用评测结果改进产品"。""")

