Q("Q34. 你怎么处理'多指标冲突'的问题——比如Faithfulness提高了但Answer Relevancy下降了？",
"""【L1·回答】
多指标冲突在AI评测中很常见，因为优化方向可能互斥。

处理流程：
① 确认是真实冲突还是假冲突——先看两次评测的条件是否一致（测试集一样吗？模型一样吗？Temperature一样吗？）
② 如果是真冲突——回到业务场景，看哪个指标的优先级更高
  例：客服场景 → Faithfulness优先（不能答错），创作场景 → Relevancy优先（对路比完全准确重要）
③ 做综合分析——不是简单比大小，而是看tradeoff是否在可接受范围
  - Faithfulness从0.85→0.92（+0.07）
  - Relevancy从0.80→0.75（-0.05）
  - 净收益+0.02 → 可以接受
④ 记录决策——这次为什么选了A放弃B，下次review时有据可查

【L2追问】如果两个指标都是核心指标，没有明显优先级怎么办？
【L2·回答】
用量化方法：给Leader和算法一个"交换比"。
"如果把Faithfulness从0.85提到0.90，可能需要牺牲0.05的Relevancy。你觉得这个交易值得吗？"

让做业务决策的人来定优先级，技术团队负责提供准确的交换比数据。
评测工程师不是最终决策者——我们提供数据，业务方做权衡。""")

Q("Q35. 你怎么设计评测的门禁（Gating）规则？",
"""【L1·回答】
评测门禁 = CI/CD流水线中的自动判断关卡。分数不达标 → 阻断发布。

设计原则：
① 底线指标一票否决——安全性<阈值（如2.0/5.0）→ 直接阻断，不管其他指标多高
② 核心指标有缓冲——Faithfulness低于基线但降幅<5% → 告警不阻断；降幅>5% → 阻断
③ 新指标渐进收紧——新上线的指标前2周只告警（收集数据），第3周开始逐步启用门禁
④ 人工覆盖通道——被阻断的发布可以有"特批"通道（需要Leader审批），避免门禁成为瓶颈

基线设定：取当前生产版本跑100次，得到均值和标准差。新版本偏离超过2个标准差 → 阻断。

【L2追问】为什么不所有指标都设门禁？
【L2·回答】
两个原因：
① 误拦成本太高——门禁太多，误拦概率叠加，导致正常发版频繁被阻
② 指标不稳定——新指标的评测逻辑还没校准好，贸然设门禁会把噪声当信号

我的原则：只对"成熟指标"设门禁。成熟的标准：Golden Dataset验证通过（Kappa>0.7）+ 连续运行1个月无异常波动。

宁可漏过（False Negative），不可误拦（False Positive）。误拦一次发版对团队信任度的伤害，比漏过一次质量问题的伤害更大。""")

Q("Q36. 你怎么让算法/业务团队真正使用你的评测结果，而不是'看了就忘'？",
"""【L1·回答】
这是评测体系落地的最大障碍——技术上做得好，但没人用。

三个策略：
① 把评测结果嵌入工作流——不只发报告，而是嵌到PR Review、发版流程中。发版前必须通过评测门禁
② 给可操作的结论——不只说"Faithfulness=0.85"，而是说"Faithfulness=0.85，其中时间类问题得分最低（0.65），建议检查Time-related Prompt"
③ 讲对比故事——"这版比上一版，安全性提升了12%，但回答完整性下降了3%。原因是新的Prompt更保守了。"

关键洞察：评测报告不是终点，是对话的开始。

【L2追问】如果算法团队说'你这评测不准，我们不认'，怎么回应？
【L2·回答】
不辩解，用数据说话：
① 请算法团队指定10条他们认可的"好回答"和"差回答"
② 用我的评测方法评测这20条
③ 对比结果——如果评测方法能正确区分好/差（>85%准确率），说明方法有效
④ 如果准确率不够 → 确实需要优化评测方法，承认问题并改进

评测方法是工具，不是真理。如果用户不认可，说明评测方法还没有证明自己的价值。验证>争辩。""")

Q("Q37. 你怎么看待AI评测的'天花板'——有些指标评测方法可能永远达不到100%准确？",
"""【L1·回答】
坦然接受。AI评测本来就不是追求完美的，就像人工评测也有偏差。

认识边界：
① 主观类指标（如'回答是否有用'）→ 评测准确率上限70-80%，因人而异
② 客观类指标（如'回答是否包含事实错误'）→ 评测准确率可达90%+
③ 安全类指标 → 可以做到高召回率，但精确率有限（容易误拦）

我的策略：
① 客观指标自动化——让机器做它擅长的事
② 主观指标辅助化——评测给参考分，最终由人判断
③ 不确定时给置信区间——不是"分数=3.8"，而是"分数=3.8±0.5（置信度中等）"

【L2追问】告诉Leader评测有局限，会不会被质疑你的能力？
【L2·回答】
恰恰相反。说"我的评测100%准确"才是外行的表现。

专业的表达：
"这套评测方法对事实类问题的判断准确率约92%，对主观类问题约75%。我会持续优化，但完全消除偏差不现实。建议关键决策保留人工复核。"

展示你理解工具的边界，比承诺做不到的事情更让Leader信任。知道什么测不了和知道什么能测，同样重要。""")

