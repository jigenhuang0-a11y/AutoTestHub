Q("Q9. 你怎么定义一个LLM的'好'？有哪些评测维度？",
"""【L1·回答】
'好'是场景相关的——客服机器人、代码生成、创意写作，'好'的定义完全不同。

通用评测维度（6维模型）：
① 功能正确性——Faithfulness/Accuracy/Relevancy，回答得对不对、有没有编造
② 安全性——有害内容过滤、越狱防御、偏见检测
③ 鲁棒性——对抗样本通过率、边界输入处理、噪声容错
④ 性能——TTFT（首Token时间）、TPOT（每Token时间）、端到端延迟、吞吐量
⑤ 用户体验——可读性、有用性、交互流畅度
⑥ 公平性——不同语言/地域/用户群体的表现差异

关键：不是所有维度同等重要。权重取决于场景。

【L2追问】给三个典型场景分配权重。
【L2·回答】
① 客服机器人：功能40% + 安全30% + 体验20% + 性能10%（不能答错，不能乱承诺）
② 代码生成：功能50% + 性能20% + 安全20% + 体验10%（能不能跑比好不好看重要）
③ 创意写作：体验50% + 功能20% + 性能20% + 安全10%（好不好看比对不对重要）

权重不是拍脑袋定的，是业务方+算法+测试三方协商，每季度review一次。""")

Q("Q10. 什么是LLM-as-Judge？怎么用它做评测？有什么风险？",
"""【L1·回答】
LLM-as-Judge = 用一个LLM当裁判，去评价另一个LLM的输出。

工作方式：
① 设计评测Prompt（含评估维度、打分标准、输出格式）
② 把被评测的LLM输出+评测Prompt一起发给Judge LLM
③ Judge按标准打分并给出理由

为什么用它：
- 人工评测成本高，规模化不可持续
- LLM对语义理解比传统NLP指标（BLEU/ROUGE）更准
- 可批量执行，适合大规模评测

【L2追问】三大风险怎么控制？
【L2·回答】
① 位置偏见——Judge可能偏好第一个回答
  → 随机打乱回答顺序，多次评测取平均
② 自我偏好——用GPT-4当Judge评测GPT-4输出，可能打高分
  → 用不同模型交叉验证（GPT-4+Claude分别打分）
③ 打分不一致——同一输入多次评测结果波动
  → 低Temperature（0.1）、多次评测取中位数、人工对标校准

LLM-as-Judge不是银弹，它是有偏差的度量工具。关键是知道偏差在哪，通过校准把偏差控制在可接受范围内。""")

Q("Q11. 传统NLP指标（BLEU/ROUGE）和LLM-as-Judge的区别？什么时候用哪个？",
"""【L1·回答】
BLEU/ROUGE：基于n-gram重叠的计算方式。
- BLEU看生成文本和参考答案有多少共同的词序列
- ROUGE看参考答案的多少内容被生成文本覆盖了
- 优点：快速、客观、可复现
- 缺点：只看字面，不懂语义——"我今天很开心"和"今天心情超好"在BLEU下完全不同

LLM-as-Judge：基于语义理解的评估方式。
- 优点：懂语义、能给具体理由、可评估复杂维度（安全性/有用性）
- 缺点：慢、贵、有随机性、有偏差

选择策略：
- 翻译/摘要 → BLEU/ROUGE为主，LLM-as-Judge为辅
- 开放式问答/对话 → LLM-as-Judge为主，BLEU/ROUGE仅作参考
- 安全评测 → LLM-as-Judge唯一选择，BLEU完全不适用

【L2追问】两者的关系是互补还是替代？
【L2·回答】
互补。实际工作中，我倾向用两层评测：
① 第一层：BLEU/ROUGE快速过滤——分数极低的直接标记为"需人工审核"，不浪费LLM-as-Judge的Token
② 第二层：LLM-as-Judge精细评估——通过第一层的才送Judge打分

这样既控制了成本，又保证了精度。传统指标做粗筛，LLM做精评。""")

Q("Q12. 你怎么评估一个评测方法本身好不好？什么叫Meta-Evaluation（元评测）？",
"""【L1·回答】
元评测 = 评测评测方法的方法。即：你怎么知道你的评测方法是正确的？

核心思路：构建Golden Dataset作为标尺。

步骤：
① 人工标注高质量评测样本——至少50条，每条有人工打分+理由
② 用你的评测方法（如LLM-as-Judge）评测这批样本
③ 对比人工评分和自动评分的差异
④ 计算一致性指标：Cohen's Kappa（分类一致性）、Pearson相关系数（分数一致性）、MAE（平均绝对误差）

评判标准：
- Kappa > 0.7 → 评测方法可信
- MAE < 0.3 → 打分偏差在可接受范围
- 偏差 > 0.5 → 评测Prompt需要优化

【L2追问】Golden Dataset本身也会过时，怎么维护？
【L2·回答】
三个策略：
① 定期review——每季度重新审视Golden Dataset，因为LLM能力在提升，原来难的问题现在可能变简单
② 动态扩充——发现新的典型case（尤其是评测方法判断错误的case），加入Golden Dataset
③ 多维覆盖——确保Golden Dataset覆盖简单/中等/困难三个难度层次，覆盖不同任务类型

元评测是做AI评测的基础课。如果你不知道你的评测方法准不准，你的评测结果就是没有意义的数字。""")

Q("Q13. 你在实际工作中怎么设计一份评测Prompt？有什么方法论？",
"""【L1·回答】
评测Prompt设计五原则：

① 明确角色——"你是一个专业的技术评测员..."（设定Judge身份）
② 细化维度——不要求打笼统分，拆成3-5个子维度每个打分
③ 量化标准——用具体锚点：1分="完全错误"、3分="部分正确"、5分="完全正确且超出预期"
④ 要求理由——每个分数必须跟一句话理由，方便后续审核Judge的合理性
⑤ 结构化输出——要求JSON输出，便于解析和统计

示例模板：
"你是一个AI质量评测员。请从以下3个维度评估回答质量：
1. 准确性（1-5分）：回答是否事实正确
2. 完整性（1-5分）：是否覆盖了用户问题的所有方面
3. 安全性（1-5分）：是否包含有害内容（1=有严重问题，5=完全安全）
请以JSON格式输出。
"

【L2追问】评测Prompt需要不断迭代吗？怎么迭代？
【L2·回答】
必须迭代。评测Prompt也是Prompt，同样受Prompt Engineering的影响。

迭代流程：
① 跑一批数据 → 分析Judge打分分布（如果有30%的case都打4分，说明区分度不够）
② 抽样人工对标 → 找出Judge和人工分歧最大的case
③ 分析原因 → 是评测维度描述不清？还是打分标准不明确？
④ 优化Prompt → 针对问题点修改 → 重新验证直到Kappa>0.7

一个评测Prompt通常要迭代3-5轮才能稳定。""")

Q("Q14. 如果让你评估一个RAG系统（检索增强生成）的答案质量，你会关注哪些指标？",
"""【L1·回答】
RAG评测比纯LLM评测多了一个维度：检索质量。

核心指标（拆成两部分）：

检索部分（Retrieval）：
① Context Precision——检索回来的文档，相关的占比多少（召回准确率）
② Context Recall——应该检索到的文档，实际检索到多少（召回覆盖率）
③ Chunk Relevance——分块策略是否合理，粒度是否合适

生成部分（Generation）：
① Faithfulness——生成的答案是否基于检索到的上下文，有没有编造
② Answer Relevancy——答案是否回应用户问题，有没有跑偏
③ Hallucination Detection——是否出现了上下文里没有的信息

综合评估：两个部分都重要。检索好但生成差 = 输出质量差；检索差但生成好 = 答案可能不正确（Garbage In Garbage Out）。

【L2追问】如果Faithfulness低怎么办？优先优化检索还是优化生成？
【L2·回答】
先诊断根因：
① 如果检索质量高（Context Precision>0.8）但Faithfulness低 → 问题在生成侧，LLM没有用好检索结果，可能是Prompt问题
② 如果检索质量低但Faithfulness高 → 问题在检索侧，LLM在"编造"看似合理的答案（最危险的情况！）

优化策略：
- 情况①：优化生成Prompt，强调"必须基于提供的上下文回答"
- 情况②：优化检索策略（调Chunk Size、换Embedding模型、加Rerank）

关键教训：Faithfulness高≠RAG好。如果检索质量差，Faithfulness高恰恰说明模型在编造——这才是最需要警惕的。""")

Q("Q15. 评测指标是越多越好吗？你怎么避免'指标通货膨胀'？",
"""【L1·回答】
不是越多越好。评测指标堆砌反而会导致：
- 评审疲劳——看板上一堆数字，没人真正关注
- 信号淹没——真正重要的指标被淹没在噪声里
- 维护成本高——每个指标都要设计Prompt、维护Golden Dataset

我的原则：核心指标不超过5个，辅助指标不超过10个。

选择标准：
① 可解释——这个指标低意味着什么具体问题，能不能指导改进
② 可对标——有没有人工评测可以校准
③ 敏感——模型或Prompt发生变化时，这个指标能感知到

反例：'回答的文学性评分'——听起来高大上，但很难定义、很难人工对标、业务方也不会看。这种指标就是噪声。

【L2追问】如果Leader要求加很多指标怎么办？
【L2·回答】
用数据说服：
① 先做指标相关性分析——新指标和现有指标如果高度相关（r>0.8），说明它在重复衡量同一个东西，没有增量价值
② 做人工对标——新指标如果人工无法可靠打分，那它就不具备可验证性
③ 提"指标分级"方案——核心指标（领导看）+ 诊断指标（技术团队看），不混在一起

让Leader理解：'少而精'的指标体系比'多而全'更有效。每个指标都是一份维护成本。""")

Q("Q16. 一个评测指标从设计到上线，你的完整流程是什么？",
"""【L1·回答】
六步流程：

① 需求定义——明确这个指标要衡量什么（如'回答是否安全'），和哪些业务目标对齐
② Prompt设计——写评测Prompt，定义打分标准和输出格式
③ Golden Dataset验证——用人标数据集验证评测Prompt的准确性，计算Kappa
④ 小批量试跑——选100条真实数据试跑，分析分数分布是否合理
⑤ 人工对标——抽样对比人工评分，验证评测可靠性
⑥ 上线监控——上线后持续监控指标趋势，异常波动触发复核

每个步骤都有明确的通过标准（Kappa>0.7、MAE<0.3、异常波动不超过2个标准差）。

【L2追问】哪个步骤最容易出问题？
【L2·回答】
第③步——Golden Dataset验证最容易流于形式。

常见问题：
- Golden Dataset质量差（标注不认真、样本量不够）→ 验证结果没有参考价值
- 只验证一次不持续维护 → 评测Prompt漂移后验证失效
- 只看平均分不看分布 → 平均分OK但个别类型case打得差

对应方案：标注质量控制（多人交叉标注）、定期重新验证（每月一次）、分段分析（按难度/类型拆开看）。

一个设计流程再完善，验证不扎实也是白搭。这是很多团队跳过又最不该跳过的步骤。""")

