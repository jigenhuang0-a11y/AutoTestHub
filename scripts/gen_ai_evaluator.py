Q("Q38. 如果让你对比GPT-4和Claude，你会设计什么样的评测方案？",
"""【L1·回答】
A/B Test框架：同一测试集 + 同一评测标准 + 双模型并行跑。

步骤：
① 构建评测集——200条以上，覆盖简单/中等/困难，覆盖不同类型的任务
② 定义评测维度——Faithfulness/Accuracy/Safety/Relevancy/Response Time/Cost
③ 双模型运行——同一prompt分别发给GPT-4和Claude
④ 评测打分——用第三个模型（如Claude当Judge评GPT-4，GPT-4评Claude，再交叉验证）
⑤ 统计分析——对比均值、方差、效应量（Cohen's d）

关键：不能只看平均分——要看分场景的表现。GPT-4可能总分高但代码场景不如Claude。

【L2追问】如果两个模型总分差不多怎么选？
【L2·回答】
总分差不多时，看细分：
① 看稳定性——谁的方差小，输出质量更稳定
② 看极端case——最差的10条case，谁的表现更差（底线在哪）
③ 看成本——同样质量下，谁的API费用更低
④ 看延迟——响应速度是否在业务承受范围内
⑤ 看风格——对特定业务场景，谁的输出风格更匹配（更保守/更有创意）

选模型不是选"最好"的，是选"最适合当前业务"的。一个总分8.0但安全性只有6.0的模型，在金融场景下不如一个总分7.5但安全性9.0的。""")

Q("Q39. 你怎么控制多模型对比评测中的'裁判偏见'？",
"""【L1·回答】
用GPT-4当Judge评测GPT-4自己的输出，可能会偏袒。

消除偏见的策略：
① 交叉裁判——用GPT-4评Claude输出、Claude评GPT-4输出，对比两个Judge的评分是否有系统性偏差
② 第三方裁判——引入第三个模型（如DeepSeek/文心一言）做独立评测，作为参照
③ 位置随机化——对比两个模型的回答时，随机打乱展示顺序
④ 人工校准——抽样50条对照人工评分，校准Judge偏差

如果发现系统性偏差（如GPT-4当Judge时对GPT-4输出平均高0.3分），后续评测加上修正系数。

【L2追问】为什么不直接全部用人工评测？
【L2·回答】
成本不允许——200条×2模型×3轮=1200次评测任务，人工做至少需要2周全职。而LLM-as-Judge可以在1小时内完成。

真实方案：LLM-as-Judge做大规模粗评（快速过滤），人工做小规模精评（校准+验证核心结论）。两者不是替代关系，是互补关系。""")

Q("Q40. 开源模型（如LLaMA/Qwen）和商业模型（GPT/Claude）的评测有什么区别？",
"""【L1·回答】
评测维度差异：

商业模型（GPT/Claude等API）：
- 评测重点：输出质量 + API稳定性 + 成本
- 不需要关注部署问题，API就是接口

开源模型：
- 额外增加：部署评测——量化后的精度损失、不同硬件上的推理速度、内存占用
- 需要关注：不同量化版本（FP16/INT8/INT4）的表现差异
- 自己部署意味着需要评测部署稳定性（服务可用性、并发能力）

在AutoTestHub中，券方式接入可以快速对比——同一个评测流程，切换模型只需改配置。这对多模型对比评测非常友好。

【L2追问】开源模型的精度损失怎么评测？
【L2·回答】
同一测试集，分别跑FP16（原始精度）、INT8、INT4三个版本 → 对比输出质量：
- 如果INT8和FP16差距<3% → 可以接受，INT8性价比更高
- 如果INT4和FP16差距>10% → 某些场景下不建议用INT4

同时评测推理速度——精度损失vs速度提升的tradeoff。有些场景（如实时对话）对延迟敏感，可以接受轻微精度损失换取更快的响应。""")

Q("Q41. 你做过模型选型吗？选型报告应该包含什么？",
"""【L1·回答】
选型报告六要素：

① 评测概览——评测了多少条数据、覆盖什么场景、用什么评测方法
② 总分对比——各模型在各维度的得分总览（表格+雷达图）
③ 场景分析——按任务类型拆开看（代码/翻译/问答/写作等），每个场景的模型排名
④ 极端case分析——各模型表现最差的前10条case是什么，暴露了什么系统性缺陷
⑤ 非功能对比——延迟、成本、并发能力、SLA
⑥ 推荐结论——推荐哪个模型、理由、注意事项（什么场景不建议用）

格式要求：一页摘要（给Leader看）+ 详细报告（给技术团队看）。Leader只看结论，技术团队看细节。

【L2追问】如果Leader说'选最便宜的就行'，你怎么回复？
【L2·回答】
用数据说话，不给个人意见：
"最便宜的模型X比最优的模型Y在Faithfulness上低15%，在安全性上低22%。如果每年因此产生5次安全事故，每次处理成本是X人力×Y天..."

把"选最便宜"的成本量化出来——最便宜的不一定总成本最低。

但如果Leader坚持——记录这次决策和理由，未来出问题时复盘有据可查。选型是业务决策，评测工程师提供数据支持。""")

