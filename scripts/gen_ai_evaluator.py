Q("Q52. 你和算法工程师意见不一致——他说'这个case不能算错'，你认为算错。怎么处理？",
"""【L1·回答】
结构化处理分歧：

① 先搞清分歧类型：
  - 事实分歧（同一个case，他认为是正确答案，你认为不是）→ 查标准/查证据
  - 标准分歧（对'什么是正确'的定义不同）→ 对齐标准
  - 边界分歧（这个case处于灰色地带）→ 讨论边界规则

② 找第三方参照：
  - 查Golden Dataset中类似case的人工标注
  - 问第三个同事的意见
  - 如果仍有分歧 → 记录为"有争议case"，评分时标注不确定性

③ 不升级到人身攻击：
  - 不是"你错了"而是"这个case的评分标准是否需要重新讨论"
  - 分歧是好事——说明评测标准不够清晰，暴露了需要完善的地方

【L2追问】如果反复出现分歧，是不是说明评测标准本身就有问题？
【L2·回答】
对。频繁分歧 = 评测标准模糊。

解决方法：把有争议的10条case整理出来，和算法团队开一个"标准对齐会"。
每条case讨论：为什么你认为对/错，标准应该是什么？最后形成共识文档。
有了共识文档后，争议case应该大幅减少。

评测标准的建设是一个持续对齐的过程，不是一次写死就完了。分歧是标准不够好的信号。""")

