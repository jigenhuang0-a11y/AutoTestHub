Q("Q19. RAG的完整流程是什么？每个环节怎么测？",
"""【L1·回答】
RAG四步流程：
(1) 检索（Retrieval）：用户Query -> Embedding -> 向量搜索 -> 返回Top-K相关文档
(2) 增强（Augmentation）：把检索到的文档拼接进Prompt
(3) 生成（Generation）：LLM基于增强后的Prompt生成回答
(4) 后处理（可选）：过滤、格式化、引用标注
测试重点：
- 检索：Recall@K、Precision@K、MRR、NDCG
- 增强：上下文是否被正确注入、截断是否正确
- 生成：Faithfulness（是否基于上下文回答）、Answer Relevancy（是否切题）
- 端到端：整体回答质量 + 延迟
【L2追问】检索环节的Recall@K和Precision@K怎么算？
【L2·回答】
假设有标注数据：Query -> 相关文档列表（人工标注）
检索返回Top-K文档：
- Recall@K = 检索到的相关文档数 / 总相关文档数
- Precision@K = 检索到的相关文档数 / K
例如：某Query有5篇相关文档，检索返回10篇(K=10)，其中4篇相关：
- Recall@10 = 4/5 = 80%
- Precision@10 = 4/10 = 40%
MRR（Mean Reciprocal Rank）：第一个相关文档的排名的倒数。
如果第一个相关文档排第3，RR=1/3；排第1，RR=1。
NDCG：考虑排名位置的相关性加权分数，越相关的文档排越前面分越高。""")

Q("Q20. RAGAS框架的四个指标分别怎么算？",
"""【L1·回答】
(1) Faithfulness（忠实度）：
- 从回答中提取所有"断言（claim）"
- 逐一检查每个断言是否能在检索到的上下文中找到支撑
- Faithfulness = 有支撑的断言数 / 总断言数
(2) Answer Relevancy（答案相关性）：
- 用LLM根据回答反向生成多个"可能的原始问题"
- 计算这些问题和原始问题的语义相似度（Embedding余弦相似度）
- 取平均值
(3) Context Precision（上下文精确率）：
- 检查Top-K检索结果中，相关的文档是否排在了前面
- 排名越靠前的相关文档贡献越大
(4) Context Recall（上下文召回率）：
- 用LLM从参考答案中提取关键信息点
- 检查这些信息点是否能在检索到的文档中找到
- Recall = 能找到的信息点数 / 总信息点数
【L2追问】这四个指标之间的关系是什么？
【L2·回答】
两两一组：
检索组（入口）：Context Precision + Context Recall -> 决定了给LLM喂的"食材"质量
生成组（出口）：Faithfulness + Answer Relevancy -> 决定了端给用户的"菜品"质量
关系：
- Context Recall低 -> 食材不够 -> Faithfulness可能高（LLM只用给的内容）但Answer Relevancy可能低（信息不全）
- Context Precision低 -> 食材杂 -> Faithfulness可能低（LLM被噪声误导）
- 两者都高 + LLM好 -> Faithfulness和Answer Relevancy都高
评测时需要四个指标一起看，单一指标会误导。""")

