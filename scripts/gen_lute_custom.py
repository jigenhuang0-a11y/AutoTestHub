Q("Q7. 如果让你研发一个AI测试工具，你的设计思路是什么？",
"""【L1·回答】
四步设计法：
(1) 需求分析——明确测什么（RAG/Agent/纯LLM）、谁用（测试工程师/算法工程师/PM）、输出什么（报告/告警/看板）
(2) 架构设计——分层解耦：评测引擎（核心算法） + 任务调度（批量执行） + 结果展示（可视化） +
数据管理（用例/结果存储）
(3) 指标设计——针对被测对象设计多维度指标（功能/安全/性能/体验），每个维度2-3个可量化KPI
(4) 迭代验证——先用最小集跑通，收集反馈，再逐步加功能
【L2追问】和通用测试框架（如Selenium/JUnit）的设计有什么区别？
【L2·回答】
核心区别：
(1) 断言方式不同——传统测试是精确断言（assertEqual），AI测试是统计断言（均值+置信区间+效应量）
(2) 评测逻辑不同——传统测试的评测逻辑是固定的（if-else），AI测试的评测逻辑本身也是AI（LLM-as-Judge），需要校准
(3) 数据依赖不同——传统测试用例是固定输入/输出对，AI测试用例需要标注数据集+评测标准
(4) 指标可解释性——传统测试的Pass/Fail很直观，AI测试的0.85分意味着什么需要业务解释
这些区别决定了AI测试工具不能简单套用传统测试框架的架构。""")

Q("Q8. 你怎么设计一个通用的评测指标体系？",
"""【L1·回答】
6维评测指标体系：
(1) 功能正确性——Faithfulness（忠实度）、Answer Accuracy（答案准确性）
(2) 安全性——越狱检测率、有害内容过滤率、Prompt注入防御率
(3) 鲁棒性——对抗样本通过率、边界输入处理率、噪声容错率
(4) 性能——TTFT（首Token时间）、TPOT（每Token时间）、端到端延迟、吞吐量
(5) 用户体验——可读性评分、有用性评分、满意度
(6) 公平性——不同输入群体（语言/地域/年龄）的表现差异
每个维度设定三级阈值：通过/警告/不通过。
【L2追问】不同业务场景的指标权重怎么定？
【L2·回答】
以三种典型场景为例：
(1) 客服机器人：功能正确性40% + 安全性30% + 用户体验20% + 性能10%（不能答错，不能乱说）
(2) 创意文案生成：用户体验50% + 功能正确性20% + 性能20% + 安全性10%（好不好看比对不对重要）
(3) 代码生成：功能正确性50% + 性能20% + 安全性20% + 用户体验10%（能不能跑比好不好看重要）
权重由业务方+算法+测试三方共同确定，每季度review一次。""")

