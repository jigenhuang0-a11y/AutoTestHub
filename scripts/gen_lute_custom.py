Q("Q23. AI推理性能的核心指标有哪些？",
"""【L1·回答】
核心指标：
(1) TTFT（Time To First Token）——用户发送请求到收到第一个Token的时间，影响"感觉快不快"
(2) TPOT（Time Per Output Token）——每个输出Token的平均生成时间（不含第一个），影响"读完要多久"
(3) 端到端延迟 = TTFT + TPOT x 输出Token数
(4) 吞吐量（Throughput）——单位时间处理的请求数或生成的Token数
(5) 首Token延迟和总延迟的P50/P95/P99分布
【L2追问】TTFT和TPOT的优化方向有什么不同？
【L2·回答】
TTFT优化方向：
- 模型加载/预热——减少冷启动延迟
- Prompt处理优化——Prompt越长TTFT越长
- 调度优化——优先分配资源给新请求
- 典型目标：<500ms（对话场景）、<2s（长文本场景）
TPOT优化方向：
- 推理加速——量化（INT8/INT4）、Flash Attention、KV Cache优化
- 批处理——Continuous Batching（连续批处理），多个请求共享一次前向传播
- 典型目标：<50ms/Token
两者是不同阶段：TTFT = 准备阶段，TPOT = 持续输出阶段。优化策略不同。""")

Q("Q24. 模型量化（Quantization）是什么？INT8/INT4量化有什么trade-off？",
"""【L1·回答】
量化 = 把模型参数从高精度（FP16/FP32）转成低精度（INT8/INT4），减少显存和加速推理。
- INT8量化：模型大小减半，精度损失<1%，几乎无感
- INT4量化：模型大小减为1/4，精度损失1-3%，需评估是否可接受
方法：
(1) PTQ（Post-Training Quantization）——训练后量化，无需重新训练
(2) QAT（Quantization-Aware Training）——训练时模拟量化，精度更高但成本大
【L2追问】什么场景适合INT4量化？什么场景不建议？
【L2·回答】
适合INT4：
(1) 资源受限场景——边缘设备、手机端部署
(2) 吞吐优先——能接受轻微质量下降换速度
(3) 大模型（70B+）——显存不够，必须量化才能跑
不建议INT4：
(1) 精度敏感任务——数学计算、代码生成（量化误差可能导致逻辑错误）
(2) 小模型（<7B）——小模型本身参数少，量化后质量下降更明显
(3) 安全性要求高——量化可能引入不可预测的偏差
建议：先用INT8跑，如果显存/速度仍不够再考虑INT4，且需充分评测量化前后的指标差异。""")

