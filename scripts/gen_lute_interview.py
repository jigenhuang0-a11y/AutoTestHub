Q("Q21. 订单状态机测试在跨境电商里为什么重要？",
"""【L1·回答】
因为跨境电商订单生命周期长、节点多。从下单、支付、风控审核、仓库拣货、发货、清关、转运、派送到签收，中间任何一个节点卡住，都会影响用户预期。
状态机测试要保证：每个状态转移都有明确的触发条件、异常情况下不会进入非法状态、用户和客服看到的状态一致。

【L2·追问】举一个订单状态机容易出Bug的场景？
【L2·回答】
「取消订单」和「发货」的竞态条件。
比如用户在前端点取消，同时仓库刚好扫描出库。如果两个操作没有加锁，可能出现用户看到「已取消」但仓库实际发了货，或者用户看到「已发货」但库存被回滚。
测试要验证并发场景下的状态一致性，必要时用接口自动化模拟并发请求。""")

