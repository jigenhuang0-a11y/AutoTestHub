Q("Q3. AutoTestHub的整体架构是怎么设计的？重点说说为什么这样分层。",
"""【L1·回答】
前后端分离：
- 前端Vue3 + Element Plus，负责页面交互；
- 后端Django + Django REST Framework，负责业务逻辑和数据；
- 执行引擎用Pytest，动态生成脚本后用subprocess执行；
- 数据层SQLite开发、PostgreSQL生产；
- AI能力统一走通义千问DashScope API。

分层原因很简单：Web层和测试执行层关注点不一样。Web是IO密集，测试执行可能调外部AI、运行时间不确定，所以分开后更稳定。

【L2·追问】执行引擎为什么不直接调用requests，而要生成Pytest脚本？
【L2·回答】
两个原因：
① Pytest是行业事实标准，Allure报告生态成熟，我不需要重复造轮子；
② 生成脚本的模式让变量替换、断言执行、结果解析都标准化，后续加新断言类型只要改配置，不用改执行引擎代码。
本质上是用「代码生成」把灵活性和稳定性兼顾了。""")

Q("Q4. AI生成用例这个功能是怎么实现的？准确率怎么样？",
"""【L1·回答】
用户粘贴接口文档或者上传Swagger JSON，后端调用qwen-plus，Prompt里写明要返回的字段：title、method、api_endpoint、headers、request_body、expected_response、assertion_rules、extract_rules。
返回的是结构化JSON，前端预览后用户可以编辑，确认后保存。

准确率上，核心字段识别率能到90%以上，但复杂业务字段还是需要人工校对。

【L2·追问】如果AI生成的用例不对，你怎么保证不会误导测试？
【L2·回答】
三层校验：
① 前端强制预览——AI生成的用例不能直接保存，必须用户看过；
② 质量数字人自动打分——低于80分标记为fail，需要修改；
③ 执行前的调试运行——单条用例可以先跑一下，确认通不通再进套件。
所以AI不是替代人，是先把60分提到80分，剩下20分人工确认。""")

Q("Q5. 接口串联测试是怎么做的？举个例子说明extract_rules和context_vars。",
"""【L1·回答】
用例A登录接口返回token，我在A里配置extract_rules，用JSONPath从data.token提取变量auth_token。
用例B获取用户信息，在headers里写Authorization: Bearer ${auth_token}。执行引擎会在跑B之前，把变量替换成A提取的真实值。
context_vars就是这套变量池，支持${var}和{{var}}两种语法，suite级别跨用例共享。

【L2·追问】如果A执行失败，B怎么处理？
【L2·回答】
默认B跳过。因为B依赖A的变量，A失败了变量不存在，B跑下去也一定是失败。
但我会在报告里明确标记「依赖失败」而不是「断言失败」，这样看报告的人知道根因在哪，不会误判。""")

Q("Q6. 质量数字人是怎么给用例打分的？能直接拦截不合格用例吗？",
"""【L1·回答】
三个维度：完整性40分、格式规范20分、内容质量40分，总分100。
- 完整性：必填字段有没有缺失，比如接口测试的URL、方法、断言；
- 格式规范：标题是否具体、URL格式对不对；
- 内容质量：有没有覆盖边界和异常场景、步骤和预期是否匹配。
还会做重复检测，相似度85%以上扣15分。

可以拦截。等级fail(<60)的用例会明确提示问题，但保存权限我没有完全封死，因为有些草稿用例需要迭代。

【L2·追问】你这套规则和团队里的测试规范是怎么对齐的？
【L2·回答】
我先收集了组内高频问题：标题模糊、漏状态码断言、异常场景覆盖少。然后把这些规则固化到质量数字人里。
每周我会抽10条AI生成的用例和人工review结果对比，调整权重。大概调了三轮后，质量数字人和人工判断基本一致了。""")

