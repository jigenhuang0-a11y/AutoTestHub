Q("Q25. 什么是LLM-as-Judge？怎么用它做评测？有什么风险和应对？",
"""【L1·回答】
LLM-as-Judge = 用一个LLM当裁判，去评价另一个LLM的输出。

工作方式：
① 设计评测Prompt（含评估维度、打分标准、输出格式）
② 把被评测LLM的输出+评测Prompt一起发给Judge LLM
③ Judge按标准打分并给出理由

价值：人工评测成本高且不可规模化，LLM对语义理解比BLEU/ROUGE更准。

【L2·追问】三大风险怎么控制？
【L2·回答】
① 位置偏见——Judge可能偏好第一个回答
  → 随机打乱回答顺序，多次评测取平均
② 自我偏好——GPT-4当Judge评GPT-4输出可能偏袒
  → 用不同模型交叉验证（GPT-4+Claude分别打分）
③ 打分不一致——同一输入多次评测得分波动
  → 低Temperature（0.1）、多次取中位数、人工定期对标校准

LLM-as-Judge不是银弹。关键不是消除偏差，而是知道偏差在哪、有多大、在什么边界内可接受。""")

Q("Q26. 传统NLP指标（BLEU/ROUGE）和LLM-as-Judge的区别？怎么配合使用？",
"""【L1·回答】
BLEU/ROUGE：基于n-gram重叠。
- 优点：快速、客观、可复现
- 缺点：只看字面不懂语义——「我今天很开心」和「心情超好」在BLEU下完全不同

LLM-as-Judge：基于语义理解。
- 优点：懂语义、给理由、可评复杂维度（安全性/有用性）
- 缺点：慢、贵、有随机性、有偏差

【L2·追问】两者怎么配合？
【L2·回答】
两层评测策略：
① 第一层：BLEU/ROUGE快速过滤 → 分数极低的直接标记「需人工审核」，不浪费Judge的Token
② 第二层：LLM-as-Judge精细评估 → 通过第一层的才送Judge打分

这样既控制了成本，又保证了精度。传统指标做粗筛，LLM做精评。
两者是互补关系，不是替代。翻译/摘要类 → BLEU为主；开放式问答/安全评测 → LLM-as-Judge为主。""")

Q("Q27. 什么是元评测（Meta-Evaluation）？为什么它很重要？",
"""【L1·回答】
元评测 = 评测评测方法的方法。核心问题：你怎么知道你的评测方法是正确的？

方法论：
① 构建Golden Dataset——至少50条人工标注样本
② 用你的评测方法评测这批样本
③ 对比人工评分和自动评分：计算Kappa、Pearson相关系数、MAE
④ 评判标准：Kappa>0.7→可信，MAE<0.3→可接受

【L2·追问】Golden Dataset会过时，怎么维护？
【L2·回答】
三个策略：
① 定期review——每季度重新审视，淘汰不具区分度的case
② 动态扩充——发现新典型case（尤其是评测方法判断错误的），加入Golden Dataset
③ 多维覆盖——确保简单/中等/困难各占1/3，覆盖不同任务类型

元评测是AI评测的基础课。不知道评测方法准不准，评测结果就是没有意义的数字。
这一点和传统软件测试是相通的——测试用例本身的正确性也需要被验证。""")

Q("Q28. 怎么设计一份好的评测Prompt？有什么方法论？",
"""【L1·回答】
评测Prompt设计五原则：

① 明确角色——「你是一个专业的技术评测员...」（给Judge身份锚点）
② 细化维度——不笼统打分，拆成3-5个子维度
③ 量化标准——用具体锚点：1分=完全错误，3分=部分正确，5分=完全正确且超出预期
④ 要求理由——每个分数必须跟一句话理由，方便审核
⑤ 结构化输出——要求JSON输出，便于解析和统计

【L2·追问】评测Prompt需要不断迭代吗？怎么迭代？
【L2·回答】
必须迭代。评测Prompt也是Prompt，同样受Prompt Engineering影响。

迭代流程：
① 跑一批数据 → 分析Judge打分分布（30%的case都打4分→区分度不够）
② 抽样人工对标 → 找出Judge和人工分歧最大的case
③ 分析原因 → 是评测维度描述不清？还是打分标准不明确？
④ 优化Prompt → 修改后重新验证直到Kappa>0.7

一个评测Prompt通常要迭代3-5轮才能稳定。这也暴露了和传统测试的区别——传统测试的断言是确定的，AI评测的「断言」（评测Prompt）需要持续校准。""")

Q("Q29. 评测指标是越多越好吗？你怎么避免「指标通货膨胀」？",
"""【L1·回答】
不是越多越好。指标堆砌导致：
- 评审疲劳——看板上全是数字，没人真正关注
- 信号淹没——重要的被淹没在噪声里
- 维护成本高——每个指标都要设计Prompt、维护Golden Dataset

我的原则：核心指标≤5个，辅助指标≤10个。

选择标准：可解释（指标低→具体什么问题）、可对标（有人工校准）、敏感（模型变了能感知）。

反例：「回答的文学性评分」——听起来高大上，但很难定义、很难对标、业务方也不看。纯噪声。

【L2·追问】Leader要加很多指标，你怎么沟通？
【L2·回答】
用数据说服：
① 做指标相关性分析——新指标和现有指标高度相关（r>0.8）→ 冗余，没有增量价值
② 做人工对标——新指标无法可靠打分 → 不具备可验证性
③ 提「分级方案」——核心指标（Leader看）+诊断指标（技术看），不混在一起

让Leader理解：「少而精」的指标体系比「多而全」更有效。每个额外指标都是一份持续的维护成本。""")

Q("Q30. 一个评测指标从设计到上线的完整流程是什么？哪个步骤最容易出问题？",
"""【L1·回答】
六步流程：
① 需求定义——这个指标衡量什么，和哪些业务目标对齐
② Prompt设计——写评测Prompt，定义打分标准和输出格式
③ Golden Dataset验证——用人标数据集验证，计算Kappa
④ 小批量试跑——100条真实数据，分析分数分布是否合理
⑤ 人工对标——抽样对比人工评分，验证可靠性
⑥ 上线监控——持续监控指标趋势，异常波动触发复核

每步有明确通过标准：Kappa>0.7、MAE<0.3、异常波动不超2个标准差。

【L2·追问】哪步最容易出问题？
【L2·回答】
第③步Golden Dataset验证最容易流于形式：
- 标注质量差（不认真、样本量不够）→ 验证结果没参考价值
- 只验证一次不持续维护 → Prompt漂移后验证失效
- 只看平均分不看分布 → 平均OK但个别类型打得差

应对：标注质量把控（多人交叉）、定期重新验证（每月一次）、分段分析（按难度/类型拆开看）。

一个设计流程再完善，验证不扎实就是白搭。这是很多团队最想跳过、又最不该跳过的步骤。""")

Q("Q31. LLM输出质量的非确定性给测试带来了什么新挑战？你怎么应对？",
"""【L1·回答】
三大挑战：
① 没有唯一正确答案——同一个问题，多个答案都可以是「对」的
② 同一输入多次输出不同——传统「输入A→预期B→断言」的模型失效
③ 评测本身的不可靠——Judge也有偏差和随机性

我的应对：
① 统计断言替代精确断言——看100次的达标率，不看一次对错
② 多次运行取稳定结果——每case跑3-5次，取中位数
③ 容忍区间设计——不同任务类型不同标准
④ 评测置信度标注——不只给分数，还给「这个分数有多可靠」

【L2·追问】这套方法怎么和传统测试管理（如TestRail/Jira）结合？
【L2·回答】
评测结果≠传统Pass/Fail，管理工具需要适配：
① 评测结果的Pass/Fail不是二值的——引入「等级」机制（PASS / WARN / FAIL / BLOCKED）
② 评测报告和Bug解耦——不是每次指标下降就提Bug，而是趋势异常才提
③ 用例管理和评测集管理分开——传统用例有确定预期，评测集只有评分标准

简单说：传统测试管理工具管的是「对不对」，AI评测需要管的是「好到什么程度」。两者不是一个维度的东西，不要强行统一。""")

