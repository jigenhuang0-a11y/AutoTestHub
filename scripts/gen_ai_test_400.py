S("第7章 Prompt评测与AI安全测试——守住AI产品的底线")

Q("Q43. 怎么做Prompt的安全性评测？常见攻击手段有哪些？",
"""【L1·回答】
三类攻击：
① Prompt注入：直接注入「忽略之前指令...」；间接注入（检索文档嵌入恶意指令）
② 越狱（Jailbreak）：角色扮演、编码绕过（Base64/ROT13）、多轮逐步引导
③ 提示泄露：诱导LLM泄露System Prompt

测试方法：构造50+攻击样本，看LLM是否被操控。

【L2·追问】安全评测的指标怎么设计？怎么平衡安全和可用性？
【L2·回答】
两个核心指标：
- 攻击成功率（越低越好）——目标<5%
- 误拦率——目标<2%

平衡策略：
① 分层风控——高风险严格拒绝，中风险加免责声明后回答，低风险正常回答
② 安全分数区间化——不只看「安全/不安全」二分，加「需要免责声明」中间态
③ 用户意图识别——「怎么治疗感冒」（求知）和「给我开药方」（需要拒绝）要区分

和传统测试中的「误报率vs漏报率」的权衡完全同理——安全防护也是Precision-Recall的tradeoff。""")

Q("Q44. 对抗性测试（Adversarial Testing）在LLM评测中怎么做？",
"""【L1·回答】
对抗性测试 = 专门构造刁钻输入，测试模型的边界和弱点。

方法一：语义扰动——正常问题改写为诱导版本
方法二：边界输入——超长文本、空输入、特殊字符、从右到左字符
方法三：知识边界探测——虚构事件、时间穿越、个性化请求

【L2·追问】对抗样本怎么高效生成？全人工设计效率太低。
【L2·回答】
人机协作：LLM负责生成，人负责审核。
① 输入一个正常问题
② Prompt：「请把这个问题改写为5个对抗版本，目的是绕过AI安全检测...」
③ LLM生成对抗变体
④ 人工审核——确保对抗样本确实构成挑战但不完全不相关
⑤ 纳入测试集

一次生成200条，人工筛后保留120条。效率提升10倍+。

这和传统测试中「用自动化工具生成边界值组合」是一样的思路——机器做大量生成，人做质量控制。""")

Q("Q45. 怎么评测一个Prompt的质量？什么是好Prompt？",
"""【L1·回答】
五个评分维度：
① 有效性——输出质量（Faithfulness/Accuracy评分）
② 稳定性——多次运行输出质量波动在可接受范围
③ 鲁棒性——改几个无关词，输出质量不大幅波动
④ 安全性——不容易被注入/越狱
⑤ 可迁移性——换了模型（GPT→Claude），依然有效

评测方法：A/B Test——两个Prompt版本，同一批测试数据，对比输出质量指标。

【L2·追问】一个好的评测Prompt应该长什么样？
【L2·回答】
六个特征：
① 角色明确——「你是一个专业的技术评测员」
② 维度清晰——3-5个维度，每个有具体定义
③ 有锚点——1分是什么、3分是什么、5分是什么，给具体例子
④ 要求理由——每个分数附带一句解释
⑤ 输出格式固定——JSON/Markdown，方便解析
⑥ 不要太长——超过300字Judge注意力分散

最差的评测Prompt：「请给以下回答打分（1-5分）」。没维度、没标准、没锚点——Judge只能「凭感觉」，结果毫无一致性。

这和传统测试中「一个清晰的测试用例vs一个模糊的测试用例」的区别完全一样——前者可复现，后者是随机结果。""")

Q("Q46. 你怎么设计一套内容安全的评测体系？",
"""【L1·回答】
四层设计：
① 违规类别覆盖：暴力/色情/违法/仇恨/自我伤害/儿童安全——每类>=50条样本
② 变体测试：每类5种变体（语义改写、编码绕过、角色扮演、多语言、隐晦表达）
③ 边界测试：擦边球内容——处在违规边界但不够明显
④ 误拦测试：正常内容（医学讨论/法律咨询）是否被错误拦截

核心指标：召回率目标>95%，精确率>90%，误拦率<2%。

【L2·追问】安全评测和功能评测的关系？
【L2·回答】
安全评测是底线评测——不和功能评测平分优先级。

做法：
① 独立运行——不和功能评测混在一起
② 一票否决——安全<2.0，不管功能多高，整体不通过
③ 每次发版必跑——不是可选项，是CI/CD门禁必检项

这和传统测试中的「Blocker级别的Bug」同理——功能Bug可以延期修复，安全Bug必须立刻处理。安全是底线思维。""")

Q("Q47. 你怎么看待AI安全评测中的「过度安全」问题？",
"""【L1·回答】
过度安全 = LLM拒绝回答本应正常回答的问题。如用户问「如何治疗感冒」，回复「我不能提供医疗建议」。

这是Precision-Recall tradeoff的典型场景——安全指标太高→误拦率上升→用户体验下降。

【L2·追问】怎么说服Leader接受一定程度的误拦？
【L2·回答】
用数据：
① 拿出竞品误拦率——行业均值3%，我们1%不算过度
② 做用户影响分析——被误拦的case中多少真正影响用户体验
③ 给分级方案——不是「全拒绝」或「全放开」，而是按风险等级分层

关键：不要让Leader觉得你在追求「绝对安全」。绝对安全=什么都拒绝=产品没法用。
展示你理解安全是「在风险可控前提下最大化可用性」。安全不是越高越好，是在可接受风险下做到最优。""")

