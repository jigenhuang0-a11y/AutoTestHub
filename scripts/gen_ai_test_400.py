Q("Q32. RAG系统评测和纯LLM评测的核心区别是什么？",
"""【L1·回答】
核心区别：RAG多了一个检索环节，评测需要拆成两部分：

检索部分：
- Context Precision——检索回来的文档，相关占比多少
- Context Recall——应该检索到的，实际检索到多少

生成部分：
- Faithfulness——生成答案是否基于检索到的上下文
- Answer Relevancy——答案是否回应用户问题
- Hallucination Detection——是否出现上下文里没有的信息

【L2·追问】Faithfulness高就一定好吗？
【L2·回答】
不一定。关键要看检索质量：
- 检索好+Faithfulness高 → RAG系统工作正常
- 检索差+Faithfulness高 → 最危险！LLM在「编造」看似合理的答案（Garbage In, Garbage Out）

所以RAG评测必须检索+生成两部分都看。Faithfulness高但Context Precision低，恰恰说明模型在「幻觉」——需要优先修检索，而不是生成。

这个教训和传统软件测试中「覆盖率」很类似——100%代码覆盖不代表代码没Bug。高Faithfulness不等于RAG好。""")

Q("Q33. RAGAS框架的核心指标是什么？你在项目中怎么用？",
"""【L1·回答】
RAGAS是专门评测RAG系统的开源框架，四个核心指标：

① Faithfulness（忠实度）——生成答案的声明有多少能从检索上下文验证
② Answer Relevancy（答案相关性）——答案是否紧贴用户问题
③ Context Precision（上下文精确度）——检索到的文档中相关的占比
④ Context Recall（上下文召回率）——应该检索到的文档实际检索到多少

在AutoTestHub中参考了RAGAS的设计但没有直接集成。现在重构的话会以RAGAS为基础+自定义扩展。

【L2·追问】RAGAS的Faithfulness计算逻辑是什么？有什么局限？
【L2·回答】
计算逻辑：
① LLM从生成答案中提取所有「声明（Claims）」
② 每条声明判断是否能从检索上下文验证
③ Faithfulness = 可验证声明数 / 总声明数

局限：
① Claim提取依赖LLM，也有偏差
② 只看「有没有依据」，不看「依据对不对」
③ 长文档可能误判——一条声明可能散在多个chunk中

补充做法：在Faithfulness之外加「事实准确率」人工抽检，用真实知识验证关键声明的正确性。""")

Q("Q34. RAG系统的幻觉和纯LLM的幻觉有什么不同？怎么测？",
"""【L1·回答】
纯LLM幻觉：模型凭空编造信息。问「某明星生日」，编一个日期。

RAG幻觉更狡猾——分两类：
① 无视上下文型——检索到了正确信息，但生成的不采用，自己编
② 上下文误读型——检索到的对，但理解错了，输出偏离原文意思

评测方法：声明级验证——把答案拆成声明，逐条和检索上下文比对。关键信息提取——数字、人名、日期等和原文比对。

【L2·追问】RAG最容易在什么情况下产生幻觉？
【L2·回答】
三个高危场景：
① 检索失败——没找到相关文档，LLM强行回答（最典型）
  解决：检索结果为空时回复「我不知道」，不硬编
② 上下文矛盾——多篇文档内容互相矛盾，LLM随便选一个
  解决：检测文档间一致性，矛盾时标注不确定性
③ 低质量上下文——检索到的内容本身错误
  解决：对检索源做质量控制

关键设计：RAG系统必须有「我不确定」的输出通道。这和传统软件测试中「优雅降级」的思路一样——系统可以不知道，但不能装知道。""")

Q("Q35. Chunk Size对RAG评测影响有多大？怎么确定最优值？",
"""【L1·回答】
Chunk Size影响很大但容易被忽略：
- 太小（128 tokens）：语义碎片化，丢失上下文，但精确度高
- 太大（1024 tokens）：上下文丰富，但噪声多，精确度低
- 最优值：通常256-512之间，取决于文档类型

评测方法：固定数据集，不同Chunk Size分别跑→对比Context Precision×Recall，找最大值。
在同一个评测集上做A/B对比，用数据说话而不是凭经验。

【L2·追问】除了Chunk Size，还有哪些影响检索质量的因素？
【L2·回答】
按影响大小排序：
① Embedding模型——不同模型向量表示不同，直接影响检索质量。需要做Embedding对比评测
② 检索策略——纯向量vs混合检索（向量+关键词），混合通常更好
③ Rerank——检索后加重排序，大幅提升Precision
④ Chunk重叠（Overlap）——相邻Chunk重叠字符数，太小切掉关键信息，太大增加冗余

这些都是可量化的——通过Context Precision和Recall对比来验证。评测工程师的价值就是把这些「经验之谈」变成「数据结论」。""")

Q("Q36. 怎么构建RAG系统的测试数据集？有什么特殊考虑？",
"""【L1·回答】
RAG测试数据集比纯LLM复杂——多了检索部分。

构建步骤：
① 构建文档库——真实业务文档，覆盖多领域多难度
② 设计问题——三类：
  - 简单查找型：直接检索能回答
  - 推理型：需要跨段落理解
  - 边界型：文档中没有答案（测试「我不知道」场景）
③ 标注预期——正确答案+应检索到的文档ID+可接受答案范围

【L2·追问】必须要包含「文档中没有答案」的问题吗？
【L2·回答】
必须。如果测试集所有问题都能在文档库找到答案 → 评测结果过于乐观。
真实用户问的问题，很大概率文档库里没有。

「没有答案」的问题测试的是RAG系统的诚实度——是否会说出「我没有找到相关信息」。
如果一个RAG系统100%的评测集都能答对，那评测集本身的覆盖度就有问题。

这和传统测试中「异常用例设计」同理——一个只测正常流程的测试用例集，无法暴露系统在异常情况下的行为。""")

Q("Q37. 多轮对话场景下的RAG评测怎么做？",
"""【L1·回答】
多轮对话和单轮的核心区别：第二轮及以后不仅依赖当前检索结果，还依赖历史对话上下文。

评测难点：
① Faithfulness需要验证答案是否同时忠于上下文+历史对话
② 对话历史中的错误会累积——第一轮微小偏差→第三轮完全离题
③ 标注成本指数级增长

我的做法：
① 逐轮评测——每轮独立打分，同时看累积效果
② 关键轮次重点评测——第1、3、5轮（奇数轮常是话题转折点）
③ 回溯法定位错误——第N轮有问题→回溯查第N轮的检索→回溯查第N-1轮对话

【L2·追问】这跟传统测试中的「链式调用测试」有什么相似之处？
【L2·回答】
非常像。传统测试中测试链式调用（A→B→C），一个中间环节出错，后续全错。
RAG多轮对话也是一样的——只是「中间环节」变成了LLM的推理和检索过程。

相似处理方式：
① 逐环节断言——每个环节（每轮对话）独立验证
② 隔离测试——单独测试某一轮，不依赖前面轮次
③ Mock依赖——Mock检索结果，单独测生成能力

软件测试的基础思维在AI测试中一样适用——隔离变量、逐层验证、Mock依赖。""")

