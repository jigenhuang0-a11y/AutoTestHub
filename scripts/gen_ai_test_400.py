Q("Q4. LLM输出是非确定性的。你怎么设计评测来应对这个问题？",
"""【L1·回答】
这是AI测试和传统测试的根本区别。传统测试：输入A→预期输出B→断言A==B。AI测试做不到。

三层策略：
① 统计断言代替精确断言——不看「这次对不对」，看「100次里多少次达标」。Faithfulness均值≥0.85且标准差<0.05才算通过
② 多次评测取稳定结果——每条case跑3-5次，取中位数或均值
③ 容忍区间设计——事实类任务严格（波动阈值<0.2），创意类任务宽松（波动阈值<0.5）

【L2·追问】一个case跑3次分数分别是3/5/2，你怎么处理？
【L2·回答】
这种情况标准差=1.25，远超正常范围（通常<0.3），说明评测本身有问题：
① 先看Judge一致性——标准差过大说明评测Prompt不够清晰
② 人工评审——抽这条case人工打分，和Judge对标
③ 优化评测Prompt——如果人工判4分但Judge打3分，细化评测维度描述
④ 标记「不稳定类」——优化后仍波动大 → 此类case从自动化评测剔除，走人工审核通道

核心原则：不要盲信Judge。Judge本身也是LLM，也有偏差和随机性。""")

