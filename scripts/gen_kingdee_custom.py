Q('Q42. 你怎么做接口的"幂等性"测试？金蝶云为什么需要幂等性？',
"""【L1·回答】
幂等性：同一个请求执行1次和执行100次，结果相同。测试方法：用相同参数连续调用3次创建凭证接口 → 断言只创建了1条凭证 → 其余2次返回409 Conflict或Idempotent-Key冲突提示。

【L2·追问】金蝶云的"生成凭证"接口，如果由于网络超时用户点了两次生成，怎么用幂等性避免生成两条重复凭证？
【L2·回答】
方案：API层引入Idempotency-Key机制——客户端发起请求时生成一个唯一Key（如UUID），服务端记录Key+结果的映射。同样的Key重复请求，直接返回第一次的结果，不做重复操作。

测试验证点：① 相同Key重复请求→返回相同结果；② 不同Key请求→正常生成新凭证；③ Key过期后（如24小时）重复使用→返回Key过期错误。三条用例覆盖幂等性的核心路径。""")

