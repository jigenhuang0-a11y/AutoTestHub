Q('Q54. 你怎么评AI输出的"一致性"——同一个问题问两次，回答应该一样吗？',
"""【L1·回答】
在财务场景下，对于"确定性问题"（如有标准答案的税务计算），回答应该每次一致；对于"非确定性问题"（如财务建议的表述风格），允许表述差异但核心结论应一致。

评测方法：同一批测试用例跑3次，对比3次输出的变化。① 确定性问题——精确对比，任何差异都是问题；② 非确定性问题——语义对比（用语义相似度），差异超过阈值标记为"不稳定"。

【L2·追问】如果AI的三次输出中，一次判断"建议通过"，两次判断"建议转人工"，这种情况算质量问题吗？
【L2·回答】
核心问题：这个审批场景本身是否"边界模糊"？如果是——金额恰好在阈值边缘、证据不够充分，那么"2次转人工+1次建议通过"的一致性在可接受范围；如果是——证据充分明确，不应该有分歧，那么这就是模型不稳定。

做评测时要标注每条用例的"确定性级别"——高确定性用例要求高一致性，低确定性用例允许低一致性。不能一刀切。""")

Q('Q55. 金蝶如何验证AI生成的"财务分析/建议"是否误导用户？',
"""【L1·回答】
财务分析/建议是高风险输出——错误的建议可能导致企业做出错误的财务决策。验证方案：

① 事实性校验——AI引用的数据、比例、阈值是否准确（如"毛利率低于行业平均"——这条信息是否基于真实数据）
② 建议合规性——AI给出的建议是否符合会计准则和税法
③ 免责声明——AI是否在输出中包含了必要的"仅供参考"声明

评测时重点检测"确定性语句"——如"你应该把这项费用计入管理费用"vs"根据会计准则，该项费用建议计入管理费用，但最终归类请以贵公司会计政策为准"。前者的确定语气在AI输出中是危险的。

【L2·追问】如果AI给出了一条错误的财务建议但加了"仅供参考"的免责声明，算通过还是失败？
【L2·回答】
失败。"仅供参考"不是免死金牌——如果AI在建议中引用了具体的数据和分析，"仅供参考"不能免责。

评测标准：① AI明确给出具体建议（如"建议将折旧年限定为10年"）——即使加了仅供参考，如果建议本身是错误的，也要判定为质量问题；② AI只提供了参考信息（如"根据《企业会计准则》，电子设备折旧年限通常为3-5年"）——加上仅供参考，这是合理的。

关键区分："我是根据自己的推理给你一个结论" vs "我给你一些信息，你自己做结论"。前者就算加了免责声明也有问题。""")

