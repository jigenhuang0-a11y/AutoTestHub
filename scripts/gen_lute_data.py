S("  1.1 Transformer架构核心（Q1-Q15）")
Q("Q1. 请详细解释Transformer的自注意力机制（Self-Attention）计算过程。",
  "Self-Attention核心公式：Attention(Q,K,V)=softmax(QK^T/√d_k)V。步骤：①从输入X通过W_Q、W_K、W_V生成Query/Key/Value向量；②计算Q与K的点积得到注意力分数矩阵；③除以√d_k缩放（防梯度消失）；④softmax归一化得注意力权重；⑤权重乘V得输出。多头注意力=并行多组Q/K/V（如8头），各组关注不同语义关系。在AutoTestHub评测中，理解注意力机制有助于分析模型对长文本关键信息的保持能力。")

Q("Q2. Transformer为什么需要位置编码？有哪些实现方式？",
  "Transformer并行处理缺少Token顺序信息。实现方式：①正弦位置编码（原论文）——PE(pos,2i)=sin(pos/10000^(2i/d))，可外推、无需训练；②可学习位置编码（BERT/GPT）——灵活但不可外推；③旋转位置编码RoPE（LLaMA/Qwen）——用旋转矩阵编码相对位置，支持外推；④ALiBi（Bloom）——线性偏置惩罚远距离Token。RoPE和ALiBi对长序列表现更好，测试时需关注不同位置编码对长文本理解的影响。")

Q("Q3. LayerNorm在Transformer中的作用？Pre-LN和Post-LN的区别？",
  "LayerNorm归一化每个样本的所有特征维度，解决内部协变量偏移，加速收敛。Pre-LN（GPT-2/LLaMA）：Norm放在子层之前（Norm→Attn→Residual），训练稳定无需warmup，现代大模型几乎都用。Post-LN（原论文）：Norm放在子层之后，效果稍好但训练不稳定需精心warmup。测试启示：不同LN位置影响模型在不同任务上的表现稳定性。")

Q("Q4. 残差连接为什么对深层Transformer至关重要？",
  "残差连接=子层输出+子层输入（x+F(x)）。作用：①缓解梯度消失——梯度可通过残差路径直接回传底层；②恒等映射——初始时子层输出接近零，保证深层至少不差于浅层；③特征复用——低层特征直接传递到高层。无残差的Transformer超12层就难训练。评测中残差质量影响深层模型信息保持能力。")

Q("Q5. FFN在Transformer中扮演什么角色？SwiGLU是什么？",
  "FFN=两层全连接+激活：FFN(x)=W2·Activation(W1·x)。作用：①Token内非线性变换（自注意力负责Token间交互）；②存储知识——FFN层存储大量事实知识（类似Key-Value记忆）。SwiGLU=用Swish门控替代ReLU的FFN变体（LLaMA/PaLM使用），效果优于传统ReLU-FFN。测试启示：FFN质量影响模型事实准确率。")

Q("Q6. 为什么大模型用Decoder-Only而非Encoder-Decoder架构？",
  "Decoder-Only优势：①训练效率——所有Token并行计算（因果掩码一次处理）；②零样本泛化——自回归训练与任意文本生成一致；③扩展性——Scaling Law上表现更稳定；④工程简单——无需区分Encoder/Decoder。Encoder-Decoder优势：双向编码理解更强，适合翻译等任务。路特创新需根据具体需求选择。")

Q("Q7. 什么是Flash Attention？解决了什么问题？",
  "Flash Attention通过IO感知算法解决Attention显存瓶颈。标准Attention的QK^T矩阵N×N读写HBM开销巨大。Flash Attention方案：①分块计算（Tiling）——Q/K/V切块在SRAM中逐块计算softmax；②重计算——反向传播重新计算注意力矩阵。效果：显存从O(N²)降到O(N)，推理速度提升2-4倍，支持更长上下文。测试时需相应调整上下文长度。")

Q("Q8. KV Cache是什么？内存占用如何计算？",
  "KV Cache=缓存历史Token的K/V矩阵，避免重复计算。公式：2×层数×KV头数×头维度×序列长度×精度字节。LLaMA-7B：2×32×32×128×2048×2(FP16)≈1GB。优化：PagedAttention（vLLM分页管理）、GQA/MQA（减少KV头数）、INT8量化Cache。性能测试中KV Cache显存是评估部署可行性的关键指标。")

Q("Q9. 什么是GQA和MQA？与标准MHA的区别？",
  "MQA=所有Query头共享1组KV头，KV Cache减少至1/h（h=头数），速度提升但可能损失质量。GQA=多Query头共享1组KV头（LLaMA-2 70B用8组），是MHA和MQA的折中。GQA在质量和速度间取得平衡，长文本推理时显存占用显著降低，适合资源受限的部署场景。")

Q("Q10. 什么是模型蒸馏？如何测试蒸馏模型质量？",
  "蒸馏=大模型（Teacher）指导小模型（Student）。方法：输出蒸馏（KL散度）、特征蒸馏、数据蒸馏。测试：①对比Student和Teacher在各维度指标差距；②关注特定领域是否明显弱于Teacher；③测试鲁棒性——蒸馏可能放大Teacher偏见。路特创新在成本优化中可能用到蒸馏。")

Q("Q11. 什么是MoE混合专家模型？如何测试？",
  "MoE=FFN层替换为多个「专家」子网络，Router选择Top-K专家处理每个Token。优势：参数多但推理计算少（稀疏激活），如Mixtral 8×7B（47B参数只用13B）。测试挑战：①负载均衡——Token分配是否均匀；②专家选择——路由是否正确；③批处理效率——稀疏性使传统批处理效率下降。需关注不同batch size下的吞吐和专家利用率。")

Q("Q12. 注意力复杂度是多少？长序列有哪些优化方案？",
  "标准注意力O(N²·d)。优化：①稀疏注意力——Sliding Window+Global Attention（Mistral）；②线性注意力——核函数近似降到O(N·d²)；③Flash Attention——IO优化；④Ring Attention——多GPU分布式处理长序列。测试时需对比不同方案在长文本任务上的效果差异。")

Q("Q13. 混合精度训练是什么？对测试有什么影响？",
  "混合精度=前向/反向用FP16（快、省显存），关键操作用FP32保精度。组件：FP16存储权重、FP32 Master Copy、Loss Scaling防underflow、AMP自动选择。对测试影响：FP16推理可能与FP32推理质量有差异，需在评测中验证。")

Q("Q14. 什么是梯度检查点？对训练有什么影响？",
  "梯度检查点=反向传播不保存所有中间激活，需要时重新计算。用计算换显存——显存显著降低，但训练慢20-30%。大模型训练几乎必需。对测试无直接影响（模型参数完全一致），只影响训练效率。")

Q("Q15. 大模型训练中loss spike的原因和应对？",
  "Loss spike=loss突然大幅升高。原因：梯度爆炸、数据异常（超长/乱码）、优化器状态破坏、FP16溢出。应对：梯度裁剪、跳过异常batch回滚模型、降低学习率、监控梯度范数。测试启示：loss spike后的checkpoint可能有隐藏质量问题，评测时应关注loss曲线。")

S("  1.2 大模型训练与微调（Q16-Q30）")
Q("Q16. 请描述大模型训练的完整流程——从数据到部署。",
  "完整流程：①数据准备——收集清洗海量文本（TB级），分词构建训练语料；②预训练——海量无标注数据自回归语言模型训练（数千GPU·月）；③指令微调SFT——高质量指令-回答数据微调；④偏好对齐RLHF/DPO——基于人类偏好优化有用性和安全性；⑤评测——标准Benchmark+业务场景评测；⑥量化与部署——压缩后部署推理服务。路特创新场景中评测贯穿全流程，各阶段需不同侧重的测试。")

Q("Q17. RLHF的完整流程？各阶段如何测试？",
  "RLHF三阶段：①SFT——高质量指令数据微调基座模型；②RM——收集人类偏好数据训练奖励模型；③PPO——用RM做奖励信号优化SFT模型。各阶段测试：SFT后测指令遵循；RM后测奖励预测准确率（与人类标注一致性）；PPO后测整体质量+安全对齐+奖励黑客检测。路特创新自研或微调模型需建立各阶段评测体系。")

Q("Q18. DPO和RLHF有什么区别？如何选择？",
  "DPO直接优化偏好数据无需训练单独奖励模型。区别：①RLHF三步（SFT+RM+PPO），DPO一步完成；②RLHF可在线迭代，DPO只适用已有数据；③DPO训练更稳定无PPO调参难题。选择：数据充足求简洁→DPO；需在线迭代→RLHF。评测时需用相同偏好测试集对比对齐效果和安全边界。")

Q("Q19. 什么是LoRA微调？如何测试效果？",
  "LoRA=预训练权重旁添加低秩矩阵（A×B，rank 8-64），只训练A和B。优势：参数高效（LLaMA-7B全参14GB→LoRA rank=8仅4MB）、快速切换多adapter、显存节省。测试：对比LoRA和全参微调在目标任务指标差距（LoRA通常达全参90-95%效果）、不同rank值效果差异。路特创新多任务场景特别适合LoRA。")

Q("Q20. QLoRA是什么？如何测试量化损失？",
  "QLoRA=LoRA+4-bit量化。额外优化：4-bit NormalFloat（专为正态分布权重）、双重量化、分页优化器。效果：单张RTX 3090可微调65B模型。测试量化损失：相同任务对比QLoRA和LoRA/全参效果差距，通常QLoRA比LoRA额外损失1-3%。路特创新GPU资源有限时QLoRA是首选。")

Q("Q21. 什么是指令微调？如何测试指令遵循能力？",
  "指令微调=在多样化「指令-回答」数据上微调，让模型学会执行各种指令。测试：①单步指令正确执行率；②多步指令全部满足率；③约束指令（格式/长度/风格）遵守率；④冲突指令处理合理性。在AutoTestHub中指令遵循是核心评测维度。")

Q("Q22. 训练数据和评测数据为什么要严格隔离？如何检测泄露？",
  "评测数据目的是衡量「未见数据」泛化能力。泄露导致模型靠记忆得高分。检测：N-gram重叠检测、MinHash去重、困惑度检测（异常低=记忆信号）、时间隔离。路特创新评测体系必须建立数据隔离机制。")

Q("Q23. 如何评估微调后是否发生灾难性遗忘？",
  "灾难性遗忘=微调后通用能力大幅下降。评估：微调前后标准Benchmark（MMLU/C-Eval）对比、遗忘率计算（>10%需关注）、按能力维度分析。缓解：微调数据混入通用数据。路特创新领域微调时必须评估通用能力保持。")

Q("Q24. 什么是模型合并？如何测试合并效果？",
  "模型合并=多微调模型权重数学融合。方法：线性插值、SLERP球面插值、TIES（修剪低幅变化）、DARE（随机丢弃delta）。测试：合并后是否兼具多能力、是否存在能力冲突。路特创新多任务需求时合并可能比多LoRA切换更高效。")

Q("Q25. 学习率和Batch Size如何设置？对模型质量的影响？",
  "学习率：预训练cosine衰减+warmup，峰值1e-4到3e-4；微调1e-5到5e-5防破坏预训练知识。Batch Size：预训练越大越好（梯度累积模拟大batch）；微调16-128。影响：过大学习率→训练不稳定/发散；过小→收敛慢；过大batch→可能泛化变差。不同超参数的模型需相同评测集对比。")

Q("Q26. 什么是Scaling Law？对测试有什么启示？",
  "Scaling Law=性能随参数量/数据量/计算量幂律关系。核心：Loss∝N^(-α)、Chinchilla最优（每参数约20Token训练数据最经济）、涌现能力（能力非线性突现）。测试启示：小模型评测不能假设大模型同样问题、需不同规模独立评测、涌现能力需专门验证。")

Q("Q27. 如何测试大模型的事实知识准确性？",
  "事实知识测试：知识覆盖（多领域问答vs知识图谱Ground Truth）、知识时效（知识截止日期问题）、知识精确度（精确vs模糊）、知识边界（诚实承认不知道）。构建分层测试集（L1常识→L2专业→L3前沿），计算分层准确率。AutoTestHub中事实准确性是基础评测维度。")

Q("Q28. 大模型上下文长度如何测试？长上下文挑战是什么？",
  "大海捞针测试：长文档中随机藏关键事实，测试不同长度（1K-128K）和位置（开头/中间/末尾）的找回率。挑战：注意力稀释、位置效应（Lost in the Middle——中间信息易被忽略）、推理延迟增长。路特创新长文档处理场景需重点测试。")

Q("Q29. 大模型训练中数据质量如何保证？脏数据有什么危害？",
  "数据质量保证：去重（MinHash/SimHash）、过滤低质量内容（困惑度过滤/分类器过滤）、去除PII敏感信息、去除有毒/有害内容、去除模板化/机器生成内容。脏数据危害：模型学偏（偏见放大）、安全对齐困难、评测指标虚高。数据质量是大模型质量的根基，测试应追溯到数据层面。")

Q("Q30. 总结：大模型原理对AI测试工程师意味着什么？",
  "意味着：①不能只测「输入→输出」——需理解内部机制设计针对性测试；②性能测试需理解推理链路——TTFT/TPOT/KV Cache等概念直接影响方案设计；③安全测试需理解攻击面——不同架构有不同安全弱点；④评测需理解模型局限——幻觉/位置偏见/知识截止需针对性评测方法；⑤成本优化需理解模型效率——量化/蒸馏/批处理选择需测试数据支撑。AI测试工程师是「理解模型如何工作并能验证其质量的人」。")

