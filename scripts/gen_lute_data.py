Q("Q31. Prompt工程在AI算法测试中的核心作用是什么？",
  "Prompt是算法测试的「测试工具」：①通过Prompt设计控制测试条件——角色/格式/行为约束；②Prompt本身就是测试对象——验证有效性和鲁棒性；③模板化实现可复现测试——相同模板确保条件一致；④对抗Prompt用于安全测试。在AutoTestHub中，评测Prompt、安全检测Prompt、用例生成Prompt都是核心组件。好的测试工程师需具备Prompt Engineering能力。")

Q("Q32. 如何设计高质量评测Prompt？关键原则？",
  "原则：①角色明确——「你是一个专业大模型评测员」；②维度清晰——列出评估维度及权重；③标准具体——每维度明确打分标准和正反例；④输出格式约束——严格JSON Schema确保可解析；⑤去偏设计——避免诱导性表述；⑥Few-shot校准——2-3个评分示例。好的评测Prompt需反复迭代优化，AutoTestHub中通过对比人工和AI评分来校准。")

Q("Q33. Chain-of-Thought在评测Prompt中怎么用？优缺点？",
  "CoT让模型展示推理步骤。优点：提高复杂推理准确率、可审查推理过程、提供可解释性。缺点：增加输出长度和延迟、可能暴露内部推理、推理可能是「合理化」而非真实推理。评测中CoT用于可解释性评测——同时评估结论和推理正确性。")

Q("Q34. Few-shot和Zero-shot在算法测试中怎么选？",
  "Zero-shot：不给示例，测试通用能力（更接近真实场景）。Few-shot：给2-3示例，测试学习和迁移能力。选择：评测通用能力用Zero-shot；评测格式遵从用Few-shot；安全测试用Few-shot展示危险边界；对比测试两种都做。AutoTestHub默认Zero-shot（更真实），特定场景用Few-shot校准。")

Q("Q35. Prompt模板版本管理和A/B测试怎么做？",
  "版本管理：Git管理，每次修改生成新版本号，记录修改原因/预期效果/历史指标，支持回滚。A/B测试：相同测试集用A/B版本分别评测，对比准确率/格式遵从率/Token效率/一致性，统计显著性检验。AutoTestHub中Agent技能系统Prompt模板支持版本管理和A/B对比。")

Q("Q36. 什么是Prompt注入防御Prompt？如何测试有效性？",
  "防御Prompt=System Prompt中添加安全指令。测试：直接注入/间接注入/多语言注入/编码注入/分步注入。指标：拦截率（恶意注入被拦截比例）和误杀率（正常对话被误判比例）。防御Prompt不是100%有效需多层防护。")

Q("Q37. 如何设计Prompt生成高质量测试数据？",
  "要点：①明确数据格式——JSON Schema和完整示例；②指定数据特征——类型/取值范围/分布比例；③要求多样性——不同风格/主题/长度；④正负样本比例——正常+边界异常；⑤包含边界和异常——空值/超长/特殊字符。验证：唯一性/格式正确性/内容合理性。AutoTestHub数据工厂已实践。")

Q("Q38. System Prompt和User Prompt区别？测试中如何利用？",
  "System Prompt设定全局行为（角色/规则/限制），优先级高于User Prompt。测试利用：安全测试尝试用User Prompt覆盖System Prompt；评测时固定System Prompt保证一致性；验证System Prompt规则是否真正生效；测试不同System Prompt对行为的影响。")

