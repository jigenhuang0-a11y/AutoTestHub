Q("Q5. 为什么选Django而不是FastAPI？两者的优劣对比要具体到开发体验和适配场景。",
"""【L1·回答】
Django胜在「全家桶」：ORM强大、Admin后台、中间件体系完善、生态成熟。适合快速搭建有复杂数据模型的后台系统。FastAPI胜在「轻量和异步」：原生async/await、自动OpenAPI文档、类型校验，适合API网关和微服务。
我选Django的原因：AutoTestHub有8个模块、几十个数据表，Django的ORM和迁移系统帮我省了大量SQL编写时间；Admin后台在开发期可以直接管理数据；DRF的ViewSet+Router开发效率极高。

【L2·追问】那你觉得什么时候应该换成FastAPI？
【L2·回答】
如果未来把执行引擎和AI调用独立成服务，我会用FastAPI写这些微服务——因为它们对异步和接口文档的要求更高。Django继续做管理后台和业务逻辑，FastAPI做高性能API层。两者可以共存。""")

Q("Q6. 为什么前后端没有用WebSocket？如果加WebSocket，你会怎么设计？",
"""【L1·回答】
没加WebSocket的原因是开发优先级：V1.0的目标是跑通核心流程，REST API + 轮询足够。WebSocket需要Django Channels + ASGI服务器，会引入额外复杂度。
如果要加，我会用Django Channels + Redis做消息通道：执行引擎每完成一个用例就push一条状态消息到前端，替代前端定时轮询的执行状态接口。Dashboard的ECharts图表也从模拟数据改成实时推送。

【L2·追问】前端轮询到底有什么具体问题？
【L2·回答】
两个问题：① 浪费请求——执行中前端每2秒轮询一次，大部分时候状态不变，这些请求是无效的；② 延迟——最坏情况下用户要等2秒才看到状态更新。对执行体验来说2秒可以接受，但如果要做"实时日志流"就必须上WebSocket了。""")

Q("Q8. 为什么模块间不完全解耦成微服务？是能力问题还是决策问题？",
"""【L1·回答】
是决策问题，当时有意识地选择单体优先。三个原因：
① 团队规模——这是一个个人项目，拆成微服务意味着要管理多个服务、多个数据库、服务发现、链路追踪，ROI太低；
② 模块间依赖——质量数字人依赖testcases模块的数据、执行引擎依赖testsuites的编排，拆开反而增加跨服务调用延迟；
③ 部署成本——单体Docker Compose一键部署 vs 微服务需要编排多个容器。

【L2·追问】那你怎么保证"将来能拆"？做了什么预留？
【L2·回答】
三个预留：
① 每个模块有独立的urls.py和views.py，边界清晰，拆成独立Django app成本低；
② 模块间通过REST API调用而非直接导入函数——比如前端触发执行是通过/api/execution/接口，不是直接调engine.py的函数；
③ 数据层已经做了SQLite/PostgreSQL切换机制，拆开后每个服务用自己的数据库也很方便。""")

Q("Q9. SQLite和PostgreSQL切换机制怎么实现的？生产环境为什么不能用SQLite？",
"""【L1·回答】
切换通过Django的DATABASES配置+环境变量控制。开发环境默认用SQLite（db.sqlite3），生产环境通过docker-compose.yml注入POSTGRES_*环境变量，Django settings检测到后自动切换。
生产不能用SQLite的核心原因：SQLite是文件级锁，写入时整个数据库被锁定，并发写入性能极差。AutoTestHub执行时会同时写入Execution记录、日志、报告文件，SQLite会变成瓶颈。

【L2·追问】你在本地开发时有没有遇到过SQLite的并发问题？
【L2·回答】
遇到过。同时开多个浏览器Tab点执行，后台报了'database is locked'。后来加了重试机制临时解决，但这个经历让我明确——SQLite只适合单用户开发和演示，生产必须切PostgreSQL。""")

