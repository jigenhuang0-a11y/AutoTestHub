Q("Q11. 如果有10个团队同时用AutoTestHub，架构上第一个瓶颈在哪里？",
"""【L1·回答】
第一个瓶颈是执行引擎的同步subprocess。10个团队同时触发执行，每个团队10个用例，就是100个subprocess，服务器CPU和内存会迅速耗尽。因为每个subprocess都是一个独立Python进程。
第二个瓶颈是Django的同步视图——AI生成用例的接口是同步调用dashscope API，一个请求要等3-5秒，10个并发请求会把Gunicorn worker占满。

【L2·追问】这两个瓶颈你打算怎么解决？
【L2·回答】
执行引擎：引入Celery+Redis异步任务队列，执行任务排队消费，限制并发worker数；
AI接口：同样改成Celery异步任务，前端提交后返回task_id，轮询任务状态；
数据库：SQLite换成PostgreSQL，增加连接池；
前端：加WebSocket实时推送任务进度，替代轮询。""")

