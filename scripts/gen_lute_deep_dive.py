Q("Q24. 为什么用subprocess而不是pytest的Python API直接调用？",
"""【L1·回答】
subprocess.run(['python', '-m', 'pytest', test_file])是进程级隔离。好处：
① 完全独立——生成的脚本有自己的Python进程，不共享Django的内存和数据库连接，一个用例崩溃不影响主进程；
② 干净——每个subprocess结束后自动释放资源，不用担心Django的数据库连接池被测试脚本占用；
③ 安全——如果生成的脚本里有死循环或内存泄漏，subprocess的timeout=600s会强制终止。

pytest的Python API（pytest.main()）是在当前进程中运行，会导致Django环境和测试环境混在一起。

【L2·追问】subprocess的缺点是什么？怎么缓解？
【L2·回答】
缺点是进程启动开销——每个执行都要fork一个新Python进程，启动+导入库大约1-2秒。缓解方案：如果同一个套件有多个用例，我会把多个test_函数生成在同一个文件里，一个subprocess执行整个套件，而不是每个用例开一个进程。这样10个用例的开销从10个进程降到1个。""")

Q("Q25. 变量替换${var}和{{var}}两种语法为什么要并存？不是一个就行了吗？",
"""【L1·回答】
设计上${var}和{{var}}功能完全相同，都做变量替换。之所以并存，是为了兼容不同的使用习惯：
- 熟悉前端模板（Vue/React）的人习惯{{var}}；
- 熟悉Shell/Postman的人习惯${var}；
- 两种语法在替换函数里用两个正则依次处理，性能没有明显差异。

【L2·追问】有没有遇到过冲突场景？
【L2·回答】
有。如果JSON请求体里本身就包含{{ }}或${ }（比如JSON Schema引用），会被误替换。解决方案是加转义字符：\\${var}或\\{{var}}不会被替换。虽然不是完美方案，但在实际使用中这种边界场景极少出现。如果未来出现高频需求，我再引入更完善的模板引擎。""")

Q("Q26. 如果执行过程中某个用例超时了（600秒），引擎怎么处理？影响后面的用例吗？",
"""【L1·回答】
subprocess.run的timeout=600秒触发后，Python会抛出TimeoutExpired异常。引擎捕获后执行两步：
① 强制终止该subprocess进程——subprocess.kill()；
② 该用例的执行结果标记为"timeout"，reason写"执行超过600秒"；
③ 继续执行下一个用例——不会因为一个用例超时就中断整条链路。

如果这个超时用例是后续用例的变量提供者（通过extract_rules），后续依赖它的用例会标记为"依赖失败"跳过，不会因为变量缺失而报奇怪的错误。

【L2·追问】600秒这个阈值怎么定的？有没有遇到过不够用的情况？
【L2·回答】
600秒是基于API测试的经验值——99%的接口调用在10秒内完成，留600秒是给极端慢的批量数据处理接口。目前没遇到不够用的情况。但如果要测长时间运行的任务（比如数据导出），应该在套件配置里支持自定义timeout，而不是全局硬编码。这是已知的待改进项。""")

