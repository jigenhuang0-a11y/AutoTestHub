Q("Q68. 你怎么定义「质量」？不是教科书定义，是你自己的理解。",
"""【L1·回答】
我的理解就一句话：质量=用户不会因为你的Bug而骂娘。
展开说三个层面：
① 功能质量——用户想做的事能做、不报错（这是底线）；
② 体验质量——能用但不爽，比如加载慢、操作繁琐（这是及格线以上的部分）；
③ 信任质量——你的App不会泄露用户隐私、不会无缘无故吞数据（这是长期口碑）。
测试最容易测到的是第一层，最难测到的是第三层。一个好的测试关注第一层、覆盖第二层、为第三层设红线。

【L2·追问】这三层在你的AutoTestHub里有对应吗？
【L2·回答】
有：功能质量→执行引擎的断言覆盖（能不能跑通）；体验质量→响应时间监控、执行耗时记录（快不快）；信任质量→AI测评师的安全检测模块（会不会泄露隐私、产生偏见）。虽然三层没有完全对等，但我设计的时候潜意识里已经在往这个方向想了。""")

Q("Q69. 你觉得「Bug数量」是衡量测试质量的指标吗？如果不是，什么才是？",
"""【L1·回答】
Bug数量不是好指标——它反映的是"发现的垃圾数量"，不是"产品的干净程度"。一个好的测试可能在前期发现了大量Bug，然后产品质量变好了、Bug数量反而下降，不能说测试变差了。
我认同的指标：
① 线上逃逸率——多少Bug是用户先发现、测试没发现的（越低越好）；
② 回归拦截率——线上Bug修复后，补的自动化用例有没有在后续版本再拦到同类问题；
③ 测试覆盖的"风险面积"——不是代码覆盖率，而是"已知风险点×测试覆盖场景"的矩阵覆盖率；
④ 提测拒绝率——开发提测后因为冒烟不过被打回去的比例（说明准入标准起了作用）。

【L2·追问】这些指标你怎么统计？有自动化吗？
【L2·回答】
线上逃逸率需要TAPD/Jira里的Bug来源字段（标记"线上反馈"vs"测试发现"），手动统计。回归拦截率可以通过AutoTestHub的execution记录统计——同一个套件的两次执行之间有没有新增的Bug。但说实话，这四个指标当前都没有完全自动化，更多是我的方法论框架。在实战中我选一个最关键的（通常是线上逃逸率），先把这个盯好。""")

Q("Q70. 你理解的「测试策略」是什么？不要只说概念，说一个具体例子的策略制定过程。",
"""【L1·回答】
测试策略就是：基于风险的分层测试资源分配。不是什么都测，而是问"这个版本最可能死在什么地方"。
举一个假设的路特创新例子——吸奶器App新版本要上线"智能记忆模式"：
风险识别：最高风险是"设备连接中断时数据丢失"（母婴场景用户情绪敏感）；其次是"新模式和旧档位冲突"；最低风险是UI文字。
策略：70%精力测设备连接稳定性+数据同步完整性（核心风险）；20%测新旧模式兼容性（中等风险）；10%测UI展示（低风险）。
P0/P1 Bug全修，P2视时间而定。

【L2·追问】如果Leader说"所有功能都要测一遍"——你怎么办？
【L2·回答】
我说"好"，但我换个方式执行——所有功能确实都"跑一遍"，但深度不一样。高风险模块做深度测试（正常+异常+边界+性能），低风险模块做广度测试（只跑正常路径）。"都测一遍"不等于"都测到一样深"。这样做既满足了Leader的"全覆盖"心理需求，又把好钢用在刀刃上。""")

Q("Q71. 自动化测试覆盖率到多少才算够？你追求100%吗？",
"""【L1·回答】
不追求100%，因为成本效益递减。我的目标是：
- 核心业务流程：90%+（登录→浏览→下单→支付这条链路必须全自动化）；
- 高频回归场景：80%+（每次发版都跑的核心用例）；
- 异常分支：30-50%（按风险优先级逐步补齐）；
- UI自动化：只覆盖核心路径（UI脚本维护成本高）。

追求100%覆盖率的团队往往陷入"为了覆盖率写无用脚本"的陷阱。一条有价值的自动化脚本>10条为了凑数的脚本。

【L2·追问】你怎么让Leader理解"不求100%"这个观点？
【L2·回答】
用数据说话。统计上一个版本：哪些Bug是自动化拦截的、哪些是手工测出来的、哪些是线上逃逸的。然后分析——如果自动化覆盖率从60%提到100%，多花的开发时间能拦住多少额外Bug？算下来增加40%覆盖率只能多拦2%的Bug，ROI一目了然。当自动化覆盖率的边际效益曲线变得平坦时，就是该停下来的信号。""")

Q("Q72. 如果让你从零搭建一个测试团队的质量体系，你会先建哪三样东西？",
"""【L1·回答】
第一：Bug管理规范——定义Bug的严重等级（P0阻断/P1严重/P2一般/P3建议）、各等级的处理时限（P0必须在2小时内响应）、Bug状态流转（新建→确认→修复中→待验证→关闭）。这是质量体系的"基础设施"，没有它一切流程都是乱的。
第二：提测准入标准——开发提测前必须通过什么检查（冒烟测试通过率100%、核心接口正常、无P0 Bug），不通过打回。目的是把质量门槛前移，不让测试成为"收垃圾"的人。
第三：回归测试用例集——一个维护良好、可自动化的核心用例集。每次发版必跑。这是质量体系的"底线守卫"。

【L2·追问】这三样东西，哪样最难推？
【L2·回答】
最难推的是提测准入标准，因为这改变了开发的行为习惯。开发习惯了"写完就扔给测试"，现在要多做一步自测。推行技巧：不要一上来就定严格标准，先定最低标准（"至少跑一遍冒烟"），让大家习惯了再加码。然后定期公布"提测通过率"，让数据推动改进，而不是靠测试的嘴皮子。""")

