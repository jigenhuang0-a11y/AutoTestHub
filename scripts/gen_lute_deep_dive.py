Q("Q59. 灰度发布阶段，你怎么设计监控指标来判断「能不能全量」？",
"""【L1·回答】
四个核心指标：
① 崩溃率/错误率——灰度用户的5xx错误率是否显著高于非灰度用户，超过阈值（比如>0.1%）自动停止灰度；
② 核心业务指标——如订单转化率、设备连接成功率，不能因为灰度导致下降超过基线值的5%；
③ 响应时间——P95延迟是否恶化，超过基线值20%需要检查；
④ 用户反馈——App Store评分、客服进线量，人工观察是否有异常投诉。

前三个是自动监控，第四个是人工观察。

【L2·追问】这些监控你怎么搭？测试来搭还是运维来搭？
【L2·回答】
测试负责定义监控指标的阈值和触发条件（因为测试最了解什么算"不正常"），运维/开发负责在监控系统（如Prometheus/Grafana或公司现有APM）里配置。测试不是自己搭监控平台，而是成为"监控需求方"——明确告诉运维"我需要监控这几个指标、阈值是多少、异常后通知谁"。这是测试右移里测试角色的转变：从"执行者"变成"质量标准的定义者"。""")

Q("Q60. 线上用户反馈和Bug做根因分析后，怎么反向补测试用例——你说说具体流程。",
"""【L1·回答】
流程分四步：
① 分类——线上Bug分三类：测试遗漏（我们有Case但没测到）、测试盲区（我们根本没有这类Case）、环境问题（非代码Bug）；
② 针对测试盲区优先处理——因为这是测试用例集的直接缺陷。比如用户反馈"在弱网环境下App数据同步丢失"，说明我们的用例里没有弱网场景；
③ 生成新用例——针对根因写具体用例（不是笼统的"测试弱网环境"，而是"2G网络下，App记录一条数据后立刻锁屏，解锁后检查云端是否同步"）；
④ 加入回归集并标记来源——用例标签打上"线上反馈#BugID"，方便以后追溯。

【L2·追问】这个流程你执行过几次？效果如何？
【L2·回答】
在中行项目期间执行过约10次。其中有一次效果特别好——一个支付超时的线上Bug，反向补了5条超时场景的用例，后续三个月的回归里又拦住了2次类似问题，拦截率40%。这让我确信：线上Bug是测试用例最好的"老师"。""")

Q("Q61. 右移有一个常见矛盾：测试团队的精力有限，线上监控占时间多了就没空做新功能测试。你怎么平衡？",
"""【L1·回答】
平衡策略：自动化优先覆盖线上高频问题。
① 不是每个线上Bug都值得回补——我按"复现频率×影响程度"做优先级排序，Top 20%的问题回补用例；
② 回补的用例必须是自动化的——手工回归线上场景不可持续，必须写进自动化脚本；
③ 建立"线上问题→自动化用例"的快速通道——从发现线上Bug到自动化脚本上线，目标24小时内完成；
④ 新功能测试和线上监控不是零和博弈——自动化脚本写好之后，线上监控就不再消耗人力，机器替你做了。

【L2·追问】24小时内完成"发现Bug→写自动化脚本→上线"，现实吗？
【L2·回答】
如果Bug已经被定位清楚、复现步骤明确，24小时内写完自动化脚本是现实的（核心路径的脚本通常不超过50行）。难题在审批流程——很多公司上线自动化脚本也要走变更审批，这个环节可能卡住。所以这个目标的实现取决于团队的自动化测试文化——如果团队认可"线上Bug的自动化回归等同于修复"，审批就不会是阻碍。""")

